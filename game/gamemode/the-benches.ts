// ---------------------------------------------------------------------------
// the benches
//
// Patrick, 21 September: "all of the vanilla tables should not let you open them
// to craft so people don't get around our system", and then, asked which of two
// readings he meant: "well some benches dont have our recipes though and yes if
// you cant yse it you shouldnt be able to open it".
//
// So one rule covers both halves of what he said. A bench opens if there is
// something you can make at it, and does not open if there is not. A forge opens
// for a smith and stays shut for a farmer. A bench none of our recipes sit on
// stays shut for everybody, which is the case he raised himself.
//
// WHY THIS IS DEFENCE AND NOT THE GATE. mp.onCraft already refuses a craft the
// half and rank on the row do not allow, and it is the gate. Crafting happens on
// the CLIENT and the server is told afterwards, so a modified client can make
// something and simply not say. Refusing to open the bench is the layer in front
// of that: the menu never appears, so there is nothing to make the craft from.
//
// The two tables below are generated by tools\Build-BenchTable.py out of
// tools\recipes.json and the FURN and ACTI records of all 101 plugins. The join
// they carry is one the server has never had: mp.onActivate is handed a base,
// a recipe names its bench by KEYWORD, and nothing joined the two because
// nothing needed to until a door had to be refused before any recipe existed.
// ---------------------------------------------------------------------------

/* Furniture base -> the bench keyword it carries. Written by
   scripts\dev\Build-BenchTable.py into its table file. mp.onActivate is handed a
   base and a recipe names its bench by keyword, and this is the only join
   between the two. A base that is not in here is not a bench. */
const BENCH_BY_BASE = table('BENCH_BY_BASE');

/*
  ===================== A RACE'S OWN GEAR IS THEIRS ========================

  Patrick, 23 September: "Riekling stuff should only be able to be made by a
  riekling", and then "We already agreed on the race gate for race based
  items so if there is anything by another race aswell it should be race
  locked". So this is a decision that was taken, not one being made here.

  THE WORD IS ON THE RECIPE AND THE ID IS ON THE PERSON. A recipe row says
  which race it belongs to as a word, because a word survives the load order
  moving; the appearance the client uploads carries raceId, which is a
  runtime form id and does not. RACES is the join, built by
  tools\Build-RaceTable.js out of the RACE records of the whole order: 258
  of them in this build, from NordRace to RieklingRace.

  A MISSING RACE REFUSES NOTHING, AND IT SHOULD NEVER BE MISSING. Patrick,
  23 September: "they have to finnoish their creation to get in the only
  thing they can save for later is class, porffesion, and sub porffesion".
  So everybody standing in the world has a face and therefore a race, and a
  blank here is a read that threw or a table that resolved nothing rather
  than a normal state. It passes anyway: this gate exists to stop a nord
  making riekling armour, not to stop somebody crafting because a property
  read failed, and a silent refusal with no race to name would be unfixable
  from the chair it happened in.
*/
var raceIndex = null;

/** The editor id of somebody's race, lowercased, or '' when it cannot be told. */
function raceOf(actorId) {
  if (!raceIndex) {
    raceIndex = {};
    var table = null;
    try {
      table = (typeof RACES !== 'undefined' && RACES && RACES.items) ? RACES.items : null;
    } catch (e) { table = null; }
    var n = 0;
    if (table) {
      for (var d in table) {
        if (!Object.prototype.hasOwnProperty.call(table, d)) { continue; }
        var id = 0;
        try { id = idOf(d); } catch (e) { id = 0; }
        // The row is { e: editor id, p: playable }. Only the name is needed
        // here: whether a race is playable decides which RECIPES carry a race
        // at all, and that is settled in the table rather than at craft time.
        var row = table[d];
        var word = row && typeof row === 'object' ? row.e : row;
        if (id) { raceIndex[id] = String(word || '').toLowerCase(); n++; }
      }
    }
    log('races:', n, 'resolved in this load order');
  }
  var a = null;
  try { a = mp.get(actorId, 'appearance'); } catch (e) { return ''; }
  if (!a || typeof a !== 'object') { return ''; }
  var id = Number(a.raceId) || 0;
  if (!id) { return ''; }
  return raceIndex[id] || '';
}

/*
  Is this recipe somebody else's race's work?

  Answers the sentence to say, or '' when there is nothing in the way. The
  row's race is a word like 'riekling' and a race's editor id is a word like
  'RieklingRace', so the test is whether the editor id carries the word: that
  catches RieklingRace and DLC2RieklingRace and every vampire and child
  variant of a race without a list of them.
*/
/*
  What to call a people out loud.

  The row carries the word a RACE record uses, because that is the only thing
  there is to compare somebody against, and 'woodelf' is not a word anybody
  says. Nobody ever reads this table except the sentence below.
*/
var RACE_CALLED = {
  nord: 'Nord', breton: 'Breton', imperial: 'Imperial', redguard: 'Redguard',
  orc: 'Orc', argonian: 'Argonian', khajiit: 'Khajiit',
  woodelf: 'Wood Elf', highelf: 'High Elf', darkelf: 'Dark Elf',
  riekling: 'Riekling'
};

function raceGate(actorId, row) {
  if (!row || !row.race) { return ''; }
  var want = String(row.race).toLowerCase();
  var mine = raceOf(actorId);
  // Nothing known about the race refuses nothing. See the note above.
  if (!mine) { return ''; }
  if (mine.indexOf(want) !== -1) { return ''; }
  var called = RACE_CALLED[want] || row.race;
  return 'That is ' + called + ' work, and their hands are not yours. ' +
         'Only a ' + called + ' can make it.';
}

/* Bench keyword -> who can make anything at it. Written by
   scripts\dev\Build-BenchTable.py into its table file.
     rows    every recipe here that reaches the server; the gate opens the
             bench for somebody craftAnswer allows one of them
     halves  each half that owns something here, at the LOWEST rank it owns
             something at: who the refusal names, and the door of a menu
             station, which has no rows
     shut    nothing can be made here by anybody (SHUT_BENCHES), and this is
             what the gate says instead of opening it */
const BENCH_ACCESS = table('BENCH_ACCESS');

/*
  WHICH TOOL A ROW'S WORK ASKS FOR (#3162).

  Patrick's A on his report page, 22 October 2026: each bench trade needs its
  own tool, worn out after 50 uses like a gathering tool. The trade is the
  row's owner, the profession whose work it is, so a Smith making a novice
  tailor's row they were taught asks for the shears, because it is tailoring,
  and a recipe nobody owns asks for nothing. The key is a key of TOOLS, or ''
  when the work needs no tool: a Warrior's or a Mage's row, an unowned one.

  THE ROW THAT MAKES ITS OWN TRADE'S TOOL ASKS FOR NONE. Every tool the gate
  asks for is made at a bench by somebody holding a tool, so the chain has to
  end somewhere, and it ends at the hammer: a smith with no hammer may forge
  one. Without that, a smith whose hammer broke could make nothing ever again
  unless another smith existed and was willing, and in a world of a few
  dozen people that is a trade closed for good. Every other tool is another
  trade's work (the shears, the alembic and the rune knife a smith's, the
  ladle a woodwright's, the axe a smith's), so this exception reaches only
  the hammer, and it is read off TOOLS rather than named.
*/
function benchToolKey(row) {
  if (!row || typeof row !== 'object') { return ''; }
  const key = String(row.owner || '').toLowerCase();
  const tool = key ? toolFor(key) : null;
  if (!tool) { return ''; }
  if (tool.accept.indexOf(String(row.out || '')) !== -1) { return ''; }
  return key;
}

/** The profession a half belongs to, or '' when the rules do not know it. */
function professionOfHalf(half) {
  const P = globalThis.__thornswoodProgression;
  const profs = (P && P.TABLE && P.TABLE.professions) || {};
  for (const prof in profs) {
    if (!Object.prototype.hasOwnProperty.call(profs, prof)) { continue; }
    if (P.halvesOf(prof).indexOf(half) !== -1) { return prof; }
  }
  return '';
}

/**
 * null when this person may open that bench, otherwise the sentence to say.
 *
 * THREE READS ANSWER YES RATHER THAN NO, and every one of them is deliberate.
 * A base this table has never heard of is not a bench and is none of our
 * business; a character block that is not loaded is a build fault; and an empty
 * BENCH_ACCESS is a table that has not been generated yet. None of those is the
 * person's fault, and a build fault must not be the reason nobody in the world
 * can stand at a forge. The same choice classGate and holdsTool both make.
 */
function benchGate(actorId, baseDesc) {
  if (!Object.prototype.hasOwnProperty.call(BENCH_BY_BASE, baseDesc)) { return null; }
  const key = BENCH_BY_BASE[baseDesc];
  if (!Object.prototype.hasOwnProperty.call(BENCH_ACCESS, key)) {
    log('no access row for bench', key, 'so it is open');
    return null;
  }
  const bench = BENCH_ACCESS[key];
  // A bench nothing can be made at, by anybody, says why and does not open,
  // so its menu never lists a thing (SHUT_BENCHES in Build-BenchTable.py: the
  // sharpening wheel and the armour table, where tempering is cut, #1384).
  // Asked before the character, because it is the same answer for everybody.
  if (bench.shut) { return String(bench.shut); }
  // No bench opens for everybody (#3080). One that holds nothing anybody's
  // trade makes (the Hearthfire building benches, whose rows nobody owns) is
  // shut for everybody, and says so before the character is read.
  const halves = bench.halves || {};
  if (!(Array.isArray(bench.rows) && bench.rows.length) && !Object.keys(halves).length) {
    return 'There is nothing anybody can make here.';
  }

  const C = globalThis.__thornswoodCharacter;
  const P = globalThis.__thornswoodProgression;
  if (!C || !C.stateOf || !P || !P.canWork) {
    log('the character block is not loaded, so the bench gate is open');
    return null;
  }
  let s = null;
  try {
    s = C.stateOf(actorId);
  } catch (e) {
    log('the bench gate threw reading the character, so it is open:', e);
    return null;
  }
  if (!s) { return null; }

  // No profession, nothing made, and the sentence says which key fixes it
  // (NO_PROFESSION_AT_A_BENCH, #1037).
  if (!s.prof) { return NO_PROFESSION_AT_A_BENCH; }

  /*
    THE DOOR ASKS THE CRAFT'S OWN QUESTION (#3080). Patrick, 21 October: "An
    open bench opens only for somebody with at least one recipe there that
    they may make." So the bench opens for somebody craftAnswer allows at
    least one of its rows: the answer the craft itself gets, and the one that
    hides the rest of the menu (handRecipesHidden), with the half, the rank, a
    race's own gear and a roll's gear all in it. A menu station (the alchemy
    lab, the arcane enchanter) holds no rows, and its door is its halves.
  */
  /*
    AND THE TOOL THAT WORK ASKS FOR (#3162). A row that is theirs opens the
    bench only when they hold its trade's tool, or it needs none (the hammer
    at the forge, benchToolKey). Nothing of theirs here that they can work
    without a tool they are missing says which tool and who makes one,
    because that is the thing between them and the bench, not their trade.
    Each trade's tool is asked once a door, not once a row.
  */
  const toolAnswers = {};
  let noTool = null;
  function toolFree(key) {
    if (!key) { return true; }
    if (!Object.prototype.hasOwnProperty.call(toolAnswers, key)) { toolAnswers[key] = toolGate(actorId, key); }
    if (!toolAnswers[key]) { return true; }
    if (!noTool) { noTool = toolAnswers[key]; }
    return false;
  }
  if (Array.isArray(bench.rows)) {
    for (let i = 0; i < bench.rows.length; i++) {
      const row = craftRow(bench.rows[i]);
      if (row && !craftAnswer(actorId, row).refusal && toolFree(benchToolKey(row))) { return null; }
    }
  } else {
    for (const half in halves) {
      if (!Object.prototype.hasOwnProperty.call(halves, half)) { continue; }
      if (P.canWork(s, half, halves[half]) && toolFree(professionOfHalf(half))) { return null; }
    }
  }
  if (noTool) { return noTool; }

  // Nothing here is theirs. Say who it belongs to rather than refusing blankly,
  // because 'you cannot use that' with no second sentence sends people to the
  // Discord.
  const who = [];
  for (const half in halves) {
    if (!Object.prototype.hasOwnProperty.call(halves, half)) { continue; }
    who.push((C.nameOf ? C.nameOf(half) : half) +
             (halves[half] === 'novice' ? '' : ' at ' + rankWord(halves[half])));
  }
  if (!who.length) { return 'There is nothing you can make here.'; }
  return 'There is nothing you can make here. That bench is ' +
         (who.length === 1 ? who[0] + '\'s' : who.slice(0, -1).join(', ') + ' and ' +
          who[who.length - 1] + '\'s') + '.';
}

/*
  The handle, and which recipes want one. Argued for at the call in mp.onCraft.

  Keyed off the family the recipe table already puts on every owned row, so this
  list is checked against real data rather than against a memory of what Skyrim
  contains: tests\test-1398-fuel.js counts the rows in each of these families and fails if
  a family here matches nothing, because a family name that has been renamed
  under it would turn this rule off without a word.
*/
const HANDLE_DESC = '15490:Thornswood-Content.esp';
/*
  CHARCOAL FOR THE FIRE, BY GRADE (#1398).

  docs/systems/professions/smith.md: "Every forge and every skyforge burns one
  charcoal. No charcoal of the grade the metal asks for, the piece is not
  made." Then the grade table, the smelter at the same grade as its metal, and
  the skyforge one grade poorer. Which grade each recipe asks for is
  FUEL_BY_RECIPE below, worked out of game\data\recipes.json by
  scripts\dev\Build-FuelTable.js, because the rows the server carries name
  neither their bench nor their metal. The rule before this read a bench off
  the row, no installed row carries one, and so no forge took any charcoal.

  The same shape as the handle: not an ingredient on the record, which would
  couple this to every smithing plugin, but taken here once the craft is
  allowed.

  THE GRADE THE TABLE NAMES, AND ONLY THAT GRADE. It used to burn the cheapest
  piece in the pack, Poor Charcoal first, whatever the metal. A hotter grade
  is not burned in place of the one asked for: the page says no charcoal of
  that grade, no piece. Skyrim's own Charcoal is the Charcoal grade, by its
  name, as it was always taken here.
*/
const CHARCOAL_GRADES = [
  null,
  { name: 'Poor Charcoal', descs: [ITEMS.charcoalT1] },
  { name: 'Charcoal', descs: [ITEMS.charcoalT2, ITEMS.charcoal] },
  { name: 'Charcoal Briquette', descs: [ITEMS.charcoalT3] },
  { name: 'Coke', descs: [ITEMS.charcoalT4] }
];

/* Written by scripts\dev\Build-FuelTable.js out of game\data\recipes.json into its table file:
   every recipe at a forge, a skyforge or a smelter, which prints the counts.
   Recipe desc -> [grade 1 to 4, the metal that asks for it or nothing, the bench]. */
const FUEL_BY_RECIPE = table('FUEL_BY_RECIPE');

/** The fuel a recipe burns, { grade, metal, bench }, or null when it burns none. */
function fuelFor(recipeDesc) {
  if (!Object.prototype.hasOwnProperty.call(FUEL_BY_RECIPE, recipeDesc)) { return null; }
  const f = FUEL_BY_RECIPE[recipeDesc];
  const grade = Number(f && f[0]);
  if (!CHARCOAL_GRADES[grade]) { return null; }
  return { grade: grade, metal: String(f[1] || ''), bench: String(f[2] || 'forge') };
}

/** How many of one item a pack holds, every stack of it counted. */
function packCount(actorId, itemDesc) {
  const baseId = idOf(itemDesc);
  if (!baseId) { return 0; }
  let inv = null;
  try { inv = mp.get(actorId, 'inventory'); } catch (e) { return 0; }
  const entries = (inv && inv.entries) || [];
  let n = 0;
  for (let i = 0; i < entries.length; i++) {
    if (entries[i] && entries[i].baseId === baseId) { n += Number(entries[i].count) || 0; }
  }
  return n;
}

/** The charcoal of exactly that grade in this pack, or '' when there is none. */
function charcoalHeld(actorId, grade) {
  const g = CHARCOAL_GRADES[grade];
  if (!g) { return ''; }
  for (let i = 0; i < g.descs.length; i++) {
    if (g.descs[i] && packCount(actorId, g.descs[i]) > 0) { return g.descs[i]; }
  }
  return '';
}

/** What is said when the grade a piece asks for is not in the pack. */
function fuelRefusal(fuel) {
  const grade = CHARCOAL_GRADES[fuel.grade].name;
  const metal = fuel.metal.replace(/\b[a-z]/g, function (c) { return c.toUpperCase(); });
  let first;
  if (fuel.bench === 'smelter') {
    first = metal ? 'Smelting ' + metal + ' burns ' + grade : 'A smelter burns ' + grade;
  } else {
    const at = fuel.bench === 'skyforge' ? 'the skyforge' : 'a forge';
    first = metal ? metal + ' at ' + at + ' burns ' + grade
                  : (fuel.bench === 'skyforge' ? 'The skyforge' : 'A forge') + ' burns ' + grade;
  }
  return first + ', and you have none. A Charburner makes it from firewood at a kiln.';
}

/*
  The four hafted families on the smith page: a war axe, a battleaxe, a
  warhammer and a mace are a metal head on a wooden haft. Other weapons was
  on this list too, and in the table that family is the woodcutter's axe and
  the drum, the flute and the lute, so the instruments were asked for a
  handle (#1398). An instrument is not a haft.
*/
const HAFTED_FAMILIES = ['War axes', 'Battleaxes', 'Warhammers', 'Maces'];

/** True when this recipe makes something fitted to a wooden handle. */
function wantsAHandle(row) {
  if (!row || typeof row !== 'object') { return false; }
  // The three tools ask for a handle in the records, so the rule must not ask
  // for a second one. Their outputs are the ones TOOLS names.
  const out = String(row.out || '');
  for (const key in TOOLS) {
    if (!Object.prototype.hasOwnProperty.call(TOOLS, key)) { continue; }
    if (TOOLS[key].give === out) { return false; }
  }
  const family = String(row.family || '');
  for (let i = 0; i < HAFTED_FAMILIES.length; i++) {
    if (HAFTED_FAMILIES[i] === family) { return true; }
  }
  return false;
}

/*
  WHAT A MASTER'S CRAFT GIVES ON TOP (#1398).

  Grand Chef, docs/systems/professions/cook.md: "At master, either half. Every
  batch yields two instead of one. The craft is still one piece of work toward
  the next rank." Master Chemist, alchemist.md, the same for a brew. Both are
  the batch the engine gives, named before it gives it (craftOutput, below,
  and cookedOutput), and the work is credited once, by the caller, as before.

  Master Weaver, docs/systems/professions/tailor.md: clothing a master tailor
  makes carries hidden armour or keeps the weather off, and Patrick's answer
  on #1398 is that the tailor picks one per garment. The pick is on the K
  panel's profession card and stays until they change it (weaveOf in the
  character block), so a garment is woven for what was lit when it was made.
  Which garment is one is written on it, the way durability writes a
  condition and a key its house: the fresh garment is named with the mark of
  the half it carries in front, the needs block's for the weather and the
  maneuvers block's for the armour, and each block reads its own mark off
  what is worn. The name is the craft's own, given by the engine through
  craftOutput (wovenOutput, below), so no garment is ever made plain and
  renamed.

  The perk is the progression block's own answer (perks), so it is held at
  master in the half somebody picked and nowhere else.
*/
function holdsPerk(actorId, key) {
  const P = globalThis.__thornswoodProgression;
  const C = globalThis.__thornswoodCharacter;
  if (!P || !P.perks || !C || !C.stateOf) { return false; }
  try { return P.perks(C.stateOf(actorId)).indexOf(key) !== -1; } catch (e) { return false; }
}

/** The mark a master weaver's garment carries now: the armour's when that is their pick, else the weather's. */
function wovenMark(actorId) {
  const C = globalThis.__thornswoodCharacter;
  let weave = '';
  try { weave = C && C.weaveOf ? C.weaveOf(C.stateOf(actorId)) : ''; } catch (e) { weave = ''; }
  if (weave === 'armour') {
    const M = globalThis.__thornswoodManeuvers;
    return M && M.WOVEN ? M.WOVEN.mark : '';
  }
  const N = globalThis.__thornswoodNeeds;
  return N && N.NEEDS && N.NEEDS.wear && N.NEEDS.wear.woven ? N.NEEDS.wear.woven.mark : '';
}

/*
  THE MARK IS NAMED BEFORE THE ENGINE GIVES THE GARMENT (#3026). A woven
  garment is a named entry of its record, and the engine fork's craftOutput
  carries the entry's name beside the record and the count (fork #93): inside
  mp.onCraft, mp.set(actorId, 'craftOutput', { name }) and OnFireSuccess adds
  the garment named, in the step that takes the inputs. Until then the engine
  could add only a plain one, so this waited on a timer for it to land,
  counted the pack to see that it had, and renamed units off the plain stack.
  A craft the engine refuses after the gamemode said yes gives nothing, named
  or not, so there is nothing to check afterwards.

  The whole batch is named: every garment of one craft was made by the same
  master on the same pick.
*/
function wovenOutput(actorId, row) {
  if (!row || typeof row !== 'object' || row.owner !== 'Tailor' || row.type !== 'ARMO') { return; }
  if (!holdsPerk(actorId, 'masterweaver')) { return; }
  const mark = wovenMark(actorId);
  if (!mark) { return; }
  const out = mp.get(actorId, 'craftOutput');
  if (!out || !(out.baseId > 0) || !(out.count > 0)) {
    log(actorId.toString(16), 'is weaving', row.name, 'and the engine names no craftOutput, so it comes out plain');
    return;
  }
  // A piece's quality (qualityOutput, #3151) is already on the name; the mark
  // goes in front of it, where the needs and maneuvers blocks read it.
  const name = mark + String(out.name || row.name || 'Garment');
  mp.set(actorId, 'craftOutput', { name: name });
  log(actorId.toString(16), 'is a Master Weaver:', out.count, name);
}

/*
  A DISH COMES OFF THE POT WITH ITS DAYS ON IT (#3163). Food that spoils
  carries its days left on its name, and the engine's craftOutput names the
  entry it gives (fork #93), so the dish lands named at its full life,
  "Venison Chop (14 days left)", in the step that takes the inputs. Asked
  after cookedOutput, so a burnt meal or a fine dish is named as what it
  is. An output somebody else named already (a woven mark) is left alone.
*/
function spoilingOutput(actorId) {
  const spoilage = globalThis.__thornswoodSpoilage;
  if (!spoilage || !spoilage.outputName) { return; }
  const out = mp.get(actorId, 'craftOutput');
  if (!out || !(out.baseId > 0) || !(out.count > 0) || out.name) { return; }
  const name = spoilage.outputName(out.baseId);
  if (!name) { return; }
  mp.set(actorId, 'craftOutput', { name: name });
}

/*
  WHAT A WEAPON OR AN ARMOUR PIECE COMES OUT AS (#3151).

  Patrick, 22 October 2026, A on #3151: crafted things come in three tiers,
  crude, fine and masterwork, at minus or plus 10%, decided by skill and
  materials. Fine is the piece as its record has it, the same as every piece
  that was not made at a bench; crude is a tenth worse and masterwork a tenth
  better, in the one number each has: a weapon's damage and an armour piece's
  rating. A garment, a ring, a staff, an arrow and a tool have no such number,
  so they are not rolled.

  SKILL AND MATERIALS ARE ONE QUESTION HERE. A row's rank is the rank of the
  dearest thing it asks for (Build-RecipeTable.ps1), so how far the maker
  stands above that rank is how much skill they bring to those materials. A
  master beating out iron rarely makes crude work; a novice on their first
  iron dagger often does. The rank is the maker's own in the half the row is,
  read before this craft's work is counted, so a sister half or a taught half
  at novice works its novice rows as a novice.

  The tier is written on the piece's name, the way durability writes its
  condition and a Master Weaver their mark: "Iron Sword (Masterwork)", and
  with a condition "Iron Sword (Masterwork) (85%)". The engine's damage
  formula reads it there (THORNSWOOD PATCH in TES5DamageFormula.cpp, fork
  #114, from the engine pin that carries it), so the marks and the 10% are
  the fork's as well as this file's. The
  name is the craft's own, given through craftOutput before the engine adds
  the piece, so nothing is made plain and renamed. The whole batch is one
  roll, as a cook's is.

  The odds are this file's, by how many ranks the maker stands above the row:
  0 is working at the edge of what you can, 3 is a master on novice stock.
*/
const CRAFT_QUALITY = {
  marks: { crude: ' (Crude)', masterwork: ' (Masterwork)' },
  odds: [
    { crude: 0.25, masterwork: 0.05 },
    { crude: 0.10, masterwork: 0.15 },
    { crude: 0.05, masterwork: 0.25 },
    { crude: 0, masterwork: 0.35 }
  ],
  lines: {
    crude: 'It comes out rough. This one is crude work, a tenth worse than a sound piece.',
    masterwork: 'It comes out true. This one is masterwork, a tenth better than a sound piece.'
  }
};
// The weapon families that strike: a staff casts, an instrument plays and a
// woodcutter's axe is a tool, so none of those is rolled.
const QUALITY_WEAPON_FAMILIES = ['Swords', 'Daggers', 'Greatswords', 'War axes', 'Battleaxes', 'Maces', 'Warhammers', 'Bows'];
const QUALITY_RANKS = ['novice', 'advanced', 'expert', 'master'];

/**
 * The tier one roll in [0, 1) gives a maker standing `margin` ranks above
 * the row: 'crude', 'fine' or 'masterwork'.
 */
function qualityTier(margin, roll) {
  const at = Math.max(0, Math.min(CRAFT_QUALITY.odds.length - 1, Math.floor(Number(margin) || 0)));
  const odds = CRAFT_QUALITY.odds[at];
  if (roll < odds.crude) { return 'crude'; }
  if (roll < odds.crude + odds.masterwork) { return 'masterwork'; }
  return 'fine';
}

/** True when this row makes a weapon that strikes or an armour piece with a rating. */
function qualityRolled(row, baseId) {
  if (!row || typeof row !== 'object') { return false; }
  const wear = globalThis.__thornswoodDurability;
  // Not knowing what a piece is means not touching it, as durability does.
  if (!wear || !wear.pieceKind) { return false; }
  const kind = wear.pieceKind(baseId);
  if (row.type === 'WEAP') { return kind === 'weapon' && QUALITY_WEAPON_FAMILIES.indexOf(String(row.family || '')) !== -1; }
  if (row.type === 'ARMO') { return kind === 'armour'; }
  return false;
}

/**
 * How many ranks the maker stands above the row, in the half the row is.
 * Read before the craft's work is credited.
 */
function qualityMargin(actorId, row) {
  const C = globalThis.__thornswoodCharacter;
  const P = globalThis.__thornswoodProgression;
  let have = 'novice';
  try { have = (P && C && C.stateOf) ? (P.rankOf(C.stateOf(actorId), String(row.half || '').toLowerCase()) || 'novice') : 'novice'; } catch (e) { have = 'novice'; }
  const mine = QUALITY_RANKS.indexOf(String(have).toLowerCase());
  const asks = QUALITY_RANKS.indexOf(String(row.rank || 'novice').toLowerCase());
  return Math.max(0, (mine < 0 ? 0 : mine) - (asks < 0 ? 0 : asks));
}

function qualityOutput(actorId, row, margin) {
  const out = mp.get(actorId, 'craftOutput');
  if (!out || !(out.baseId > 0) || !(out.count > 0)) { return; }
  if (!qualityRolled(row, out.baseId)) { return; }
  const tier = qualityTier(margin, Math.random());
  if (tier === 'fine') { return; }
  const name = String(row.name || 'Piece') + CRAFT_QUALITY.marks[tier];
  mp.set(actorId, 'craftOutput', { name: name });
  log(actorId.toString(16), 'made', out.count, name, 'standing', margin, 'rank(s) above it');
  notify(actorId, CRAFT_QUALITY.lines[tier]);
  say(actorId, CRAFT_QUALITY.lines[tier]);
}

/*
  WHAT A COOK'S CRAFT GIVES (#2906, and Grand Chef, #1398).

  Patrick, 20 October 2026, B on #2906: a cook comes out burnt, plain or fine,
  the odds by the cook's rank, and a fine dish's help lasts 30 minutes instead
  of 20. A record cannot carry per-copy data and the eat event names only a
  record, so each quality is its own record (FOOD_GROUPS.quality), and the
  craft has to give that record instead of the recipe's dish.

  mp.onCraft could only allow or refuse a craft, so the only way to give a
  burnt meal was to let the engine add the dish and then take it back out of
  the pack and put another in: noticing the damage and undoing it. The engine
  fork's craftOutput (fork #92) is the fix at the cause: inside this handler,
  mp.get(actorId, 'craftOutput') is { baseId, count }, the recipe's output, and
  mp.set names what the engine gives instead, in the step that takes the
  inputs. A refused craft gives nothing whatever was named.

  The rank is the cook's own in the half the recipe is (a confectioner at the
  pot is making their sister half's novice work, at novice). One roll per
  craft, so Grand Chef's second portion is the same quality as the first: the
  engine gives the one record twice. A row with no fine record (a tea, the
  mill's flour, a paste) is not rolled, and a Grand Chef still makes two.

  The crafting menu shows the dish until it closes: the client does not apply
  the server's inventory while that menu is open (fork b137d0d6), so the
  burnt or fine record replaces it when the menu closes, as any correction
  does.
*/
function cookedOutput(actorId, row) {
  if (!row || row.owner !== 'Cook') { return; }
  const out = mp.get(actorId, 'craftOutput');
  if (!out || !(out.baseId > 0) || !(out.count > 0)) {
    log(actorId.toString(16), 'is cooking', row.name, 'and the engine names no craftOutput, so it comes out as the recipe has it');
    return;
  }
  const N = globalThis.__thornswoodNeeds;
  const C = globalThis.__thornswoodCharacter;
  const P = globalThis.__thornswoodProgression;
  let rank = 'novice';
  try { rank = (P && C && C.stateOf) ? (P.rankOf(C.stateOf(actorId), String(row.half || '').toLowerCase()) || 'novice') : 'novice'; } catch (e) { rank = 'novice'; }
  const made = (N && N.cookedAs) ? N.cookedAs(out.baseId, rank, Math.random()) : { baseId: out.baseId, quality: 'plain' };
  const chef = holdsPerk(actorId, 'grandchef');
  const count = chef ? out.count * 2 : out.count;
  if (made.baseId === out.baseId && count === out.count) { return; }
  mp.set(actorId, 'craftOutput', { baseId: made.baseId, count: count });
  log(actorId.toString(16), 'cooked', row.name, 'at', rank + ':', made.quality, count, chef ? '(Grand Chef)' : '');
  const line = (N && N.NEEDS && N.NEEDS.cookQuality && N.NEEDS.cookQuality.lines[made.quality]) || '';
  if (line) {
    notify(actorId, line);
    say(actorId, line);
  }
}

function onCraftRoll(actorId, roll) {
  const gate = globalThis.__thornswoodRolls;
  if (gate && typeof gate.has === 'function') {
    try { return !!gate.has(actorId, roll); } catch (e) { return false; }
  }
  const C = globalThis.__thornswoodCharacter;
  if (!C || !C.stateOf) { return false; }
  let s = null;
  try { s = C.stateOf(actorId); } catch (e) { return false; }
  if (!s) { return false; }
  const list = s.rolls;
  if (Array.isArray(list)) { return list.indexOf(roll) !== -1; }
  if (list && typeof list === 'object') { return !!list[roll]; }
  return false;
}

function craftAnswer(actorId, row) {
  const out = { refusal: null, note: null, credit: null };

  /*
    SOME THINGS NOBODY MAKES, AND THAT IS ASKED BEFORE ANYTHING ELSE.

    Patrick, 23 September: "Remove all of the house pars except for a key", and
    asked which: "I mean the craftable stuff in the forge hinges, locks, nails,
    iron fittings, etc". Separately, about the same menu: "Locks shouldn't be
    craftable".

    These are HearthFires house building stock, and nobody builds a HearthFires
    house here: property is claimed with a deed and a door takes the key its
    holder cut from a mold. So a nail is a thing you can make and then do
    nothing whatever with.

    It is first because there is no rank at which a nail becomes useful and no
    profession that wants one. Answering "you are not a smith yet" to somebody
    reaching for a hinge would be a promise that one day they can have it.

    The row carries the sentence, out of $NOBODY_MAKES in the generator, so the
    reason a thing is refused is written beside the decision to refuse it
    rather than here. The menu entry stays: a bench is the BNAM keyword on the
    record and no server code moves it.
  */
  if (row && row.nobody) {
    out.refusal = 'Nobody makes that here. ' + String(row.nobody);
    return out;
  }

  /*
    A RACE'S OWN GEAR IS THEIRS, AND IT IS ASKED BEFORE ANY OF THE LEARNING.

    Before the profession, the half and the rank, because those three are
    about what somebody has learned and this one is about what they are. A
    nord who has mastered every half of smithing still cannot make riekling
    armour, and telling them about their rank first would be answering a
    question they did not ask.

    See raceGate: a row with no race passes, and a person whose race cannot
    be read passes, so this only ever refuses when both are known and they
    disagree.
  */
  const wrongRace = raceGate(actorId, row);
  if (wrongRace) {
    out.refusal = wrongRace;
    return out;
  }
  const C = globalThis.__thornswoodCharacter;
  const P = globalThis.__thornswoodProgression;
  if (!C || !C.stateOf || !P) {
    log('the character block is not loaded, so the craft gate is open');
    return out;
  }
  let s = null;
  try {
    s = C.stateOf(actorId);
  } catch (e) {
    log('the craft gate threw reading the character, so it is open:', e);
    return out;
  }
  if (!s) { return out; }

  // The rulebook's spelling is capitalised in the table and lower case in the
  // rules. The rules are the side that decides, so the table's words are folded
  // to theirs and never the other way round.
  const half = String(row.half || '').toLowerCase();
  const owner = String(row.owner || '').toLowerCase();
  const rank = String(row.rank || 'novice').toLowerCase();
  const made = String(row.name || 'that');
  const halfName = C.nameOf ? C.nameOf(half) : half;

  /*
    NO PROFESSION, NOTHING MADE (#1037). Every row that reaches this gate is
    somebody's work, so a character with no profession is refused it and told
    to press K. What is nobody's work never gets here; see
    NO_PROFESSION_AT_A_BENCH.
  */
  if (!s.prof) {
    out.refusal = NO_PROFESSION_AT_A_BENCH;
    return out;
  }

  /*
    A ROW WITH A ROLL IS NOT A PUBLIC BENCH.

    Embassy gear is the embassy roll. Thalmor and Justiciar gear is the
    remnant roll. The cut file names both. A person who is not on that
    roll is refused before profession and rank, because the bench is not
    where these are found. The roll is read off the character when it has
    one, or off __thornswoodRolls.has(actorId, roll) when a roll list is
    installed. The embassy and remnant block installs it (#1390), and an
    admin writes both rolls, so the public bench makes none of them.
  */
  if (row && row.roll) {
    const roll = String(row.roll);
    let on = false;
    try { on = onCraftRoll(actorId, roll); } catch (e) { on = false; }
    if (!on) {
      const made = String(row.name || 'that');
      out.refusal = roll === 'embassy'
        ? 'Only the embassy roll may make a ' + made + '. It is not made at a public bench.'
        : 'Only the Thalmor remnant roll may make a ' + made + '. It is not made at a public bench.';
      return out;
    }
  }


  /*
    The one question every other gate in this file asks, and it answers three of
    the allowed cases at once: your own half at or under your rank, your sister
    half at novice, and a half a Master of another profession taught you, which
    is also novice and never more. classes.md: 'You get the novice work of your
    sister half for nothing. An Edgewright knows how to beat out plain iron
    plate, because anybody who works a forge does.'
  */
  if (P.canWork(s, half, rank)) {
    // A staff also needs its spell learned from a tome (THE STAFF SPELLS, #967).
    const staff = globalThis.__thornswoodStaffSpells;
    const unlearned = (staff && row.spell) ? staff.refusal(s, row) : null;
    if (unlearned) {
      out.refusal = unlearned;
      return out;
    }
    out.credit = half;
    return out;
  }

  const mineName = professionName(s.prof);

  // Your own half, above your rank. The rank it wants is named, because 'no' on
  // its own is how somebody decides the server is broken.
  if (s.half === half) {
    const have = P.rankOf(s, half);
    out.refusal = 'A ' + made + ' is ' + rankWord(rank) + ' ' + halfName + '\'s work' +
                  (have ? ' and you are ' + rankWord(have) + ' ' + halfName : '') +
                  '. Rank comes from doing the work.';
    return out;
  }

  // Your sister half, above novice. classes.md: 'What they cannot do is go any
  // further than novice with it ... For that you find a Platewright, and that is
  // a conversation rather than a menu.'
  const sister = s.half ? P.sisterOf(s.prof, s.half) : null;
  if (sister && sister === half) {
    // Taken on by a Master who still stands (#1388): the rank is the wall now.
    const climbing = !!(C.masterFor && C.masterFor(actorId, s, half));
    out.refusal = climbing
      ? 'A ' + made + ' is ' + rankWord(rank) + ' ' + halfName + '\'s work and you are ' +
        rankWord(P.rankOf(s, half) || 'novice') + ' ' + halfName + '. A Master took you on in it, ' +
        'so rank comes from doing the work.'
      : 'A ' + made + ' is ' + halfName + ' work past novice, and ' + halfName +
        ' is your sister half. You get the novice of it for nothing and no ' +
        'further. A Master ' + halfName + ' can take you on, from the prompt they see when they look at you.';
    return out;
  }

  // A half a Master of another profession taught you. It never leaves novice,
  // so this is a ceiling rather than a rank to climb, and the sentence says so.
  if (P.rankOf(s, half)) {
    out.refusal = 'A ' + made + ' is ' + halfName + ' work past novice. What a Master ' +
                  'teaches you outside your own profession never goes further than ' +
                  'novice, however long you spend on it.';
    return out;
  }

  // Another profession entirely. The half that can make it and the profession
  // that half belongs to are both named, because the answer to this one is a
  // person and the point is to go and find them.
  out.refusal = 'Only ' + aWord(halfName) + ' can make a ' + made + '. That is ' +
                professionName(owner) + ' work and you are ' + aWord(mineName) + '. Ask one.';
  return out;
}


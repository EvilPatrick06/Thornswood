/**
 * The RECIPES_SET_IN_GAME recipe a craft with no recipe id is, or null: the
 * same output, the same bench keyword, and exactly the counts it asks now
 * (an input it takes to 0 is not sent at all), summed per item.
 */
function recipeSetInGame(craftedItemBaseId, workbenchId, inputs) {
  if (!Array.isArray(inputs)) { return null; }
  var own = Object.prototype.hasOwnProperty;
  var outDesc = null;
  var benchKey = '';
  try {
    outDesc = mp.getDescFromId(craftedItemBaseId);
    var benchBase = mp.get(workbenchId, 'baseDesc');
    if (benchBase && own.call(BENCH_BY_BASE, benchBase)) { benchKey = String(BENCH_BY_BASE[benchBase]); }
  } catch (e) {
    return null;
  }
  if (!outDesc || !benchKey) { return null; }
  var held = {};
  for (var i = 0; i < inputs.length; i++) {
    var entry = inputs[i] || {};
    var d = null;
    try { d = mp.getDescFromId(Number(entry.baseId) || 0); } catch (e) { d = null; }
    if (!d) { return null; }
    held[d] = (held[d] || 0) + (Number(entry.count) || 0);
  }
  for (var desc in RECIPES_SET_IN_GAME) {
    if (!own.call(RECIPES_SET_IN_GAME, desc)) { continue; }
    var row = RECIPES_SET_IN_GAME[desc];
    if (row.out !== outDesc || row.bench !== benchKey) { continue; }
    var want = {};
    for (var n = 0; n < row.inputs.length; n++) {
      if (row.inputs[n][2]) { want[row.inputs[n][0]] = (want[row.inputs[n][0]] || 0) + row.inputs[n][2]; }
    }
    var same = Object.keys(want).length === Object.keys(held).length;
    for (var k in want) { if (own.call(want, k) && held[k] !== want[k]) { same = false; } }
    if (same) { return desc; }
  }
  return null;
}


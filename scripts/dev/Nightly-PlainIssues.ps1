<#
  Nightly-PlainIssues.ps1

  Names every issue and issue comment made in the last day that is not
  written plain. Run by .github/workflows/nightly.yml in its step "Issues
  and comments written plain", with GH_TOKEN and REPO set:

      .\scripts\dev\Nightly-PlainIssues.ps1 -Run

  Exits 1 when it names anything, so the night is red and Nightly-Issue.ps1
  puts it on the board. Whoever wrote the named issue or comment rewrites it.

  WHY (#3692). When the repository goes public, every issue and every comment
  goes public with it, open or closed. Patrick decided on 26 Oct that every
  issue written the old way (a lane's byline, an audit layout, a Claude Code
  footer) is re-filed and deleted before the flip, and then that every new
  issue and comment is written plain from now on, so it never needs that
  (his answer A on q-3692-new-issue-style). On 26 Oct 393 issues were opened
  in one day the old way. Developer-Guide.md "How an issue and a comment are
  written" is the rule; this is its check.

  WHAT IT NAMES. In an issue's title or body, or a comment's body:
    - an agent footer: "Generated by/with Claude Code", a Claude Code session
      link, a Claude-Session line. The one exception is $PlatformFooter, the
      exact closing line the platform itself puts under everything a cloud
      Claude writes. It is added on every path and cannot be turned off
      (checked 27 Oct), so it is taken off before the rules are read, and
      neither counts as a line nor hides anything above it;
    - a byline: a line opening "Found by the", "Written by", "New evidence
      from" or "Claimed by a Claude", or a lane's audit or lane named
      ("Anvil audit", "Smeagle lane"), or a Claude thread, session or Desk;
    - a Windows profile path with a name in it (C:\Users\<name>);
    - a Discord id (17 to 20 digits);
    - from the team (owner, member or collaborator), a body longer than the
      plain shape: more than 8 lines that are not blank. A comment whose
      first line is "Test task:" or "Roadmap:" keeps its own shape and is
      not measured. A stranger's report and a bot's text are not measured.
  Nothing made before $Floor is read: that is the re-file's work (#3692).

  The token is the workflow's own GITHUB_TOKEN (issues: read). Nothing here
  prints it. tests\test-nightly-plain-issues.ps1 runs this against a
  stand-in GitHub.
#>
[CmdletBinding()]
param(
    # Read GitHub and say what is not plain. Without it the script only
    # defines its functions, which is how the harness loads it.
    [switch]$Run
)

$ErrorActionPreference = 'Stop'

# The rule starts here: what was made before is re-filed under #3692.
$Floor = [DateTime]::Parse('2026-10-27T13:00:00Z').ToUniversalTime()

# What the platform adds under every issue and comment a cloud Claude writes:
# a blank line, a rule and one italic line, at the very end and nowhere else.
# Written anywhere else, or in any other words, it is still named.
$PlatformFooter = '(?:\r?\n)*---\r?\n_Generated by \[Claude Code\]\(https://claude\.ai/code\)_\s*$'

# Lines of a plain body: two to five, a "Done when" line, and room for a
# list of steps a person would write. Over this it is the audit layout.
$MaxLines = 8

# One call to the GitHub API. The tests replace Invoke-RestMethod under it.
function Invoke-PlainApi {
    param([string]$Path)
    $h = @{ Authorization = "Bearer $env:GH_TOKEN"; 'User-Agent' = 'thornswood-nightly'; Accept = 'application/vnd.github+json' }
    # Into a variable first: Invoke-RestMethod hands a JSON array down the pipe
    # as one object, and returning the variable hands on its items.
    $r = Invoke-RestMethod -Method GET -Headers $h -Uri "https://api.github.com/repos/$env:REPO/$Path"
    return $r
}

# Every item of a list GitHub pages, 100 to a page, until a page comes back
# short. $Path carries a query of its own; the page is added to it.
function Get-PlainPages {
    param([string]$Path)
    $all = @()
    $page = 1
    while ($true) {
        $batch = @(Invoke-PlainApi ($Path + '&per_page=100&page=' + $page))
        $all += $batch
        if ($batch.Count -lt 100) { break }
        $page++
        if ($page -gt 50) { throw ('More than 5,000 in ' + $Path + ': stopped reading pages.') }
    }
    return $all
}

# The rules one text breaks, by name. $Team: written by the owner, a member
# or a collaborator, and not a bot, so the plain shape's length applies.
function Test-Plain {
    param([string]$Text, [bool]$Team)
    $t = [string]$Text -replace $PlatformFooter, ''
    $broken = @()
    if ($t -match '(?i)generated (by|with) \[?claude code|claude\.ai/code/session|(?m)^\s*claude-session:') { $broken += 'agent footer' }
    if ($t -match '(?im)^\W*(found by the|written by|new evidence from|claimed by a claude)\b' -or
        $t -match '(?i)\b(anvil|herald|waystone|wyrd|smeagle|codex|grok)( bot)? (audit|lane)s?\b' -or
        $t -match '(?i)\bclaude (thread|session)s?\b|\b(cloud|local) desk\b') { $broken += 'byline' }
    if ($t -match '(?i)\b[a-z]:\\+users\\+(?!(public|default)\b)(?!<)[a-z0-9._-]+') { $broken += 'personal path' }
    if ($t -match '(?<![\d.])\d{17,20}(?![\d.])') { $broken += 'Discord id' }
    if ($Team -and $t -notmatch '^\s*(Test task:|Roadmap:)') {
        $lines = @($t -split "`r?`n" | Where-Object { $_.Trim() }).Count
        if ($lines -gt $MaxLines) { $broken += ('longer than the plain shape (' + $lines + ' lines)') }
    }
    return $broken
}

function Test-Team {
    param($Item)
    $assoc = [string]$Item.author_association
    $bot = $Item.user -and ([string]$Item.user.type -eq 'Bot')
    return (-not $bot) -and (@('OWNER', 'MEMBER', 'COLLABORATOR') -contains $assoc)
}

# The issues and comments made since $Since (and never before $Floor) that
# break a rule. Pull requests are left out: only an issue's text is re-filed.
function Find-NotPlain {
    param([DateTime]$Now = [DateTime]::UtcNow, [double]$Hours = 26)
    $since = $Now.AddHours(-$Hours)
    if ($since -lt $Floor) { $since = $Floor }
    $stamp = $since.ToString('yyyy-MM-ddTHH:mm:ssZ')
    $isNew = { param($i) ([DateTime]$i.created_at).ToUniversalTime() -ge $since }
    $issues = @(Get-PlainPages ('issues?state=all&since=' + $stamp) | Where-Object { -not $_.pull_request -and (& $isNew $_) })
    $comments = @(Get-PlainPages ('issues/comments?since=' + $stamp) | Where-Object { & $isNew $_ })
    $found = @()
    foreach ($i in $issues) {
        $b = @(Test-Plain -Text ([string]$i.title + "`n" + [string]$i.body) -Team $false)
        # The title is one line; only the body is held to the length.
        $len = @(Test-Plain -Text ([string]$i.body) -Team (Test-Team $i))
        $all = @($b + @($len | Where-Object { $_ -like 'longer*' }) | Select-Object -Unique)
        if ($all.Count) { $found += [pscustomobject]@{ Kind = 'issue'; Number = [int]$i.number; Where = ('issue #' + $i.number); Rules = $all } }
    }
    foreach ($c in $comments) {
        $all = @(Test-Plain -Text ([string]$c.body) -Team (Test-Team $c))
        $n = [int](([string]$c.issue_url) -replace '^.*/', '')
        if ($all.Count) { $found += [pscustomobject]@{ Kind = 'comment'; Number = $n; Where = [string]$c.html_url; Rules = $all } }
    }
    return [pscustomobject]@{ Found = $found; Issues = $issues.Count; Comments = $comments.Count; Since = $stamp }
}

if ($Run) {
    $r = Find-NotPlain
    foreach ($f in $r.Found) { Write-Host ("::error::{0} is not written plain: {1}" -f $f.Where, ($f.Rules -join ', ')) }
    Write-Host ("read {0} issue(s) and {1} comment(s) made since {2}" -f $r.Issues, $r.Comments, $r.Since)
    if ($r.Found.Count) {
        Write-Host ("{0} not written plain; Developer-Guide.md, ""How an issue and a comment are written"", says how. Rewrite each, keeping the evidence in the private ops repo." -f $r.Found.Count)
        exit 1
    }
    Write-Host 'every new issue and comment is written plain'
    exit 0
}

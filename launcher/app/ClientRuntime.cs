namespace Thornswood
{
    /// <summary>
    /// The six files that ARE the SkyMP client runtime, checked against the
    /// record that built them and put back when they are not.
    ///
    /// WHY THIS EXISTS, and it is one tester's evening.
    ///
    /// 22 September. A brand new install, every row on the Play page green
    /// except one: "skymp5-client.js is missing, reinstall Thornswood", and
    /// Play greyed out. What it took to get in was purging mods in Vortex,
    /// switching to another server's profile, running THAT server's launcher
    /// repair, logging in to a character there, purging again, switching back
    /// to Thornswood, and only then pressing Scan and Fix here. Patrick:
    /// "well our launcher should fix it all for them and let them in."
    ///
    /// It should, and it already had everything it needed to. A pack carries
    /// all six of these files: Ship-Rules.ps1 reads client-build.json into
    /// $ShipClientFiles and the recorded build at a path in that record ships
    /// whatever else the filters say. What was missing was anything on this
    /// side that noticed the file was gone and went and got it.
    ///
    /// WHY THE OLD CHECK COULD NOT DO IT. Checks.ClientPatched opened the
    /// bundle and searched the TEXT for "THORNSWOOD PATCH". That is the check
    /// from before 20 September, when there was no record and, in this repo's
    /// own words, our copies were told apart from another launcher's "by
    /// nothing but a comment we had written into them". The record exists now.
    /// Sync-Client.ps1 verifies against it and Ship refuses a release whose
    /// client is not the recorded build. The launcher was the last place still
    /// asking the old question, and a text search cannot tell you WHICH build
    /// you have, only that somebody wrote our name in it once.
    ///
    /// THE RECORD TRAVELS IN THE EXE. records\client-build.json is embedded by
    /// Build-Launcher.ps1, the same way ui.xaml and Thornswood.ini are. That is
    /// deliberate rather than shipping it as a file: the launcher and the
    /// client go out in one release, so the launcher that is running IS the
    /// statement of which client belongs beside it, and there is no second copy
    /// on disk to drift.
    /// </summary>
    static class ClientRuntime
    {
        public class Entry
        {
            public string Rel = "";
            public string Sha = "";
            public long Bytes;
        }

        static List<Entry> recorded;
        static string recordError = "";

        /// <summary>
        /// The record, parsed once. An empty list means the exe was built
        /// without it, which is a build fault and is reported as one rather
        /// than quietly becoming "everything is fine".
        /// </summary>
        public static List<Entry> Recorded()
        {
            if (recorded != null) return recorded;
            var list = new List<Entry>();
            try
            {
                string text = null;
                Assembly asm = Assembly.GetExecutingAssembly();
                using (Stream s = asm.GetManifestResourceStream("client-build.json"))
                {
                    if (s != null)
                        using (var sr = new StreamReader(s))
                            text = sr.ReadToEnd();
                }
                if (string.IsNullOrEmpty(text))
                {
                    recordError = "this launcher was built without client-build.json";
                }
                else
                {
                    /*
                      Hand read rather than deserialised, because the files
                      object is keyed BY PATH: every key is a different name, so
                      there is no class to bind it to and DataContractJson has
                      nothing to work with. The file is generated by
                      New-ClientBuildRecord.ps1 and its shape is ours, so a
                      pattern over it is honest here in a way it would not be
                      over somebody else's document.
                    */
                    var m = Regex.Matches(text,
                        "\"([^\"]+\\\\\\\\[^\"]+)\"\\s*:\\s*\\{\\s*\"sha256\"\\s*:\\s*\"([0-9a-fA-F]{64})\"\\s*,\\s*\"bytes\"\\s*:\\s*([0-9]+)");
                    foreach (Match g in m)
                    {
                        var e = new Entry();
                        // JSON escapes every backslash, so the key arrives as
                        // Data\\SKSE\\... and has to come back to one each.
                        e.Rel = g.Groups[1].Value.Replace("\\\\", "\\");
                        e.Sha = g.Groups[2].Value.ToLowerInvariant();
                        long b;
                        long.TryParse(g.Groups[3].Value, out b);
                        e.Bytes = b;
                        list.Add(e);
                    }
                    if (list.Count == 0)
                        recordError = "client-build.json is embedded but no files could be read out of it";
                    Match f = Regex.Match(text, "\"fork\"\\s*:\\s*\"(https://github\\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+)\"");
                    Match c = Regex.Match(text, "\"forkCommit\"\\s*:\\s*\"([0-9a-fA-F]{7,40})\"");
                    if (f.Success && c.Success)
                        source = f.Groups[1].Value + "/tree/" + c.Groups[1].Value.ToLowerInvariant();
                }
            }
            catch (Exception ex)
            {
                recordError = "client-build.json could not be read: " + ex.Message;
            }
            recorded = list;
            return recorded;
        }

        public static string RecordError { get { Recorded(); return recordError; } }

        static string source = "";

        /// <summary>
        /// The source of the six files beside this launcher: the public fork
        /// at the commit the embedded record names. The AGPL asks for the
        /// source to be offered where the server is used (section 13), and
        /// the launcher is where everybody who connects starts, so its
        /// sidebar links here (#421). Empty when the record names no fork or
        /// commit, which is the build fault RecordError already reports.
        /// </summary>
        public static string SourceUrl { get { Recorded(); return source; } }

        public static string Sha256Of(string file)
        {
            try
            {
                // ReadWrite on purpose, the same reason ClientPatched had it:
                // SkyrimPlatform holds these open while the game runs and
                // anything stricter is denied while it does.
                using (var fs = new FileStream(file, FileMode.Open, FileAccess.Read,
                                               FileShare.ReadWrite | FileShare.Delete))
                using (var h = SHA256.Create())
                {
                    byte[] d = h.ComputeHash(fs);
                    var sb = new StringBuilder();
                    for (int i = 0; i < d.Length; i++) sb.Append(d[i].ToString("x2"));
                    return sb.ToString();
                }
            }
            catch { return ""; }
        }

        /// <summary>Full path in Thornswood's own game folder.</summary>
        static string Full(string rel) { return Path.Combine(Paths.Game, rel); }

        /// <summary>
        /// Which of the six are not the recorded build, and why.
        ///
        /// A size check first because it costs nothing, then the hash. A file
        /// that is there and the right size and the wrong hash is the case
        /// that matters most and is the one the old text search could not see.
        /// </summary>
        public static List<string> Wrong(out List<string> missing)
        {
            missing = new List<string>();
            var wrong = new List<string>();
            foreach (Entry e in Recorded())
            {
                string p = Full(e.Rel);
                if (!File.Exists(p)) { missing.Add(e.Rel); continue; }
                long len = -1;
                try { len = new FileInfo(p).Length; }
                catch
                {
                    // There and unreadable is not something to stop somebody
                    // over: the game holds these open and a locked file is the
                    // normal case while it runs.
                    continue;
                }
                if (len != e.Bytes) { wrong.Add(e.Rel); continue; }
                string sha = Sha256Of(p);
                if (sha.Length == 0) continue;           // locked, see above
                if (!sha.Equals(e.Sha, StringComparison.OrdinalIgnoreCase)) wrong.Add(e.Rel);
            }
            return wrong;
        }

        /// <summary>True when all six are the recorded build.</summary>
        public static bool Good()
        {
            if (Recorded().Count == 0) return true;   // no record, no verdict
            List<string> missing;
            return Wrong(out missing).Count == 0 && missing.Count == 0;
        }

        // -------------------------------------------------------------- heal

        /// <summary>
        /// Put back whatever is not the recorded build, from the two places a
        /// correct copy can be, and say what happened.
        ///
        /// ONE: Profile\Keep. Keep already holds skymp5-client.js and its five
        /// neighbours for any file one of this build's updates wrote, which is
        /// the cheapest and quietest source and needs no network at all.
        ///
        /// TWO: the packs on the feed. Every pack carries all six, so the
        /// newest one that has a given file is a correct copy of it. This takes
        /// the file out of the zip and puts it in place WITHOUT going through
        /// Updater.Install, deliberately: Install writes applied.txt and a file
        /// list, and a pack recorded as applied a second time puts its own
        /// files out of reach of its own Remove. Nothing about which packs are
        /// applied changes here. This is a repair, not an update.
        ///
        /// Returns how many files it put back.
        /// </summary>
        public static int Heal(Config cfg, Action<string> log)
        {
            if (log == null) log = delegate { };
            if (Recorded().Count == 0)
                {
                    log("There is no record of which client belongs here, so nothing can be checked or put back. " +
                        (RecordError.Length > 0 ? RecordError : ""));
                    return 0;
                }

            List<string> missing;
            List<string> wrong = Wrong(out missing);
            var want = new List<string>();
            want.AddRange(missing);
            want.AddRange(wrong);
            if (want.Count == 0) return 0;

            log("The client runtime is not the build this launcher expects. Putting " +
                want.Count + (want.Count == 1 ? " file" : " files") + " back.");

            int done = 0;

            // ONE: the kept copies.
            for (int i = want.Count - 1; i >= 0; i--)
            {
                string rel = want[i];
                try
                {
                    if (!Keep.HasKept(rel)) continue;
                    string kept = Path.Combine(Keep.Dir, rel);
                    if (!File.Exists(kept)) continue;
                    if (!Matches(rel, Sha256Of(kept))) continue;
                    string dest = Full(rel);
                    string dir = Path.GetDirectoryName(dest);
                    if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
                    File.Copy(kept, dest, true);
                    log("  " + Path.GetFileName(rel) + " restored from your kept copy.");
                    want.RemoveAt(i);
                    done++;
                }
                catch (Exception ex) { log("  " + Path.GetFileName(rel) + ": " + ex.Message); }
            }
            if (want.Count == 0) { log("The client runtime is back to the recorded build."); return done; }

            // TWO: the client runtime asset, which is the address rather than
            // the search. One download, all six files, named by fork commit.
            VersionDoc v = null;
            try { v = Updater.Check(cfg); }
            catch (Exception ex) { log("  could not ask the update feed: " + ex.Message); return done; }
            if (v == null)
            {
                log("  the update feed could not be reached, so the rest could not be fetched.");
                return done;
            }

            if (v.clientRuntime != null && !string.IsNullOrEmpty(v.clientRuntime.url))
            {
                string zip = null;
                try
                {
                    log("  fetching the client runtime" +
                        (string.IsNullOrEmpty(v.clientRuntime.forkCommit)
                            ? "" : " " + v.clientRuntime.forkCommit) + "...");
                    zip = Updater.Fetch(cfg, v.clientRuntime.url, v.clientRuntime.sha256, log);
                    done += TakeFrom(zip, want, "the client runtime", log);
                }
                catch (Exception ex) { log("  the client runtime download failed: " + ex.Message); }
                finally { if (zip != null) { try { File.Delete(zip); } catch (Exception ex) { Swallow.Note("ClientRuntime.Heal, deleting temp zip", ex); } } }
            }
            if (want.Count == 0) { log("The client runtime is back to the recorded build."); return done; }

            // THREE: the packs, for a launcher newer than the feed, or a feed
            // written before the asset above existed.
            try
            {
                if (v.packs == null || v.packs.Length == 0)
                {
                    log("  nothing else on the feed carries them.");
                    return done;
                }
                /*
                  Newest last in the feed, so walk it backwards: the most
                  recent pack holding a file is the one to take it from.

                  AND NOT ALL THE WAY BACK. A pack only carries what CHANGED,
                  and the feed listed 218 of them on 22 September going back to
                  10 September. Walking the lot would download two hundred zips
                  to look inside them, which is worse than saying plainly that
                  it could not be found. The client runtime changes rarely, so
                  if it is not in the last few dozen packs it is not coming
                  from a pack at all and something else is wrong.
                */
                int looked = 0;
                for (int pi = v.packs.Length - 1; pi >= 0 && want.Count > 0; pi--)
                {
                    if (looked >= 40)
                    {
                        log("  looked in the last 40 updates and did not find " + want.Count +
                            " of them. Say so in the Discord with this text.");
                        break;
                    }
                    Pack p = v.packs[pi];
                    if (p == null || string.IsNullOrEmpty(p.url)) continue;
                    looked++;
                    string zip = null;
                    try
                    {
                        log("  looking in " + p.Title + "...");
                        zip = Updater.Fetch(cfg, p.url, p.sha256, log);
                        done += TakeFrom(zip, want, p.Title, log);
                    }
                    catch (Exception ex) { log("  " + p.Title + ": " + ex.Message); }
                    finally { if (zip != null) { try { File.Delete(zip); } catch (Exception ex) { Swallow.Note("ClientRuntime.Heal, deleting temp zip", ex); } } }
                }
            }
            catch (Exception ex) { log("  could not ask the update feed: " + ex.Message); }

            if (want.Count == 0) log("The client runtime is back to the recorded build.");
            else log("Could not put back " + want.Count + " of them. Say so in the Discord with this text.");
            return done;
        }

        /// <summary>
        /// Take whatever of `want` this zip carries, verify each one, and
        /// remove the ones that landed from the list.
        ///
        /// Shared by the client runtime asset and the pack walk, because the
        /// two differ only in where the zip came from. Every file is hashed
        /// AFTER it is written: a download whose checksum was right can still
        /// hold the wrong build of a file, and a Client row that went green on
        /// somebody else's build is worse than one that stayed red.
        /// </summary>
        static int TakeFrom(string zip, List<string> want, string where, Action<string> log)
        {
            int took = 0;
            using (ZipArchive ar = ZipFile.OpenRead(zip))
            {
                for (int i = want.Count - 1; i >= 0; i--)
                {
                    string rel = want[i];
                    ZipArchiveEntry en = Find(ar, rel);
                    if (en == null) continue;
                    string dest = Full(rel);
                    try
                    {
                        string dir = Path.GetDirectoryName(dest);
                        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
                        // In a game folder made of hard links, writing over a
                        // linked file rewrites Vortex's copy in the Steam
                        // install with it. Updater.Install breaks the link
                        // first for exactly this and so does this.
                        if (File.Exists(dest)) { try { OwnGame.Unshare(dest); } catch (Exception ex) { Swallow.Note("ClientRuntime.TakeFrom, Unshare " + dest, ex); } }
                        en.ExtractToFile(dest, true);
                    }
                    catch (Exception ex)
                    {
                        log("  " + Path.GetFileName(rel) + " could not be written: " + ex.Message);
                        continue;
                    }
                    if (!Matches(rel, Sha256Of(dest)))
                    {
                        log("  " + Path.GetFileName(rel) + " came out of " + where +
                            " and is not the recorded build; leaving it.");
                        continue;
                    }
                    // Pack synchronization skips runtime files. Refresh the
                    // retained script only after checking the extracted bytes,
                    // or Keep.Restore can roll this repair back before Play.
                    Keep.Remember(new[] { rel });
                    log("  " + Path.GetFileName(rel) + " restored from " + where + ".");
                    want.RemoveAt(i);
                    took++;
                }
            }
            return took;
        }

        static bool Matches(string rel, string sha)
        {
            if (string.IsNullOrEmpty(sha)) return false;
            foreach (Entry e in Recorded())
                if (e.Rel.Equals(rel, StringComparison.OrdinalIgnoreCase))
                    return sha.Equals(e.Sha, StringComparison.OrdinalIgnoreCase);
            return false;
        }

        /// <summary>
        /// The entry for a path inside a pack.
        ///
        /// A PACK PUTS EVERY GAME FILE UNDER "game/", and the first version of
        /// this looked for a bare "Data/...". It found nothing in a pack that
        /// was carrying all six, which is the quietest possible failure: the
        /// launcher downloads the right zip, looks inside, and says the file is
        /// not there. Caught by opening pack-20260922-2202.zip and reading the
        /// entry names instead of trusting what they ought to be.
        ///
        /// Updater.Install is the other half of this convention: "game\" is
        /// stripped and the rest lands under Paths.Game, "profile\" goes to the
        /// golden profile. Change the two together.
        ///
        /// The bare form is still accepted, because a zip that carries a plain
        /// Data path is a correct copy of the file whatever else is true of it,
        /// and refusing it would be refusing the thing we came for. Slashes
        /// either way: a zip written on Windows can hold either.
        /// </summary>
        static ZipArchiveEntry Find(ZipArchive ar, string rel)
        {
            string bare = rel.Replace('\\', '/');
            string prefixed = "game/" + bare;
            foreach (ZipArchiveEntry en in ar.Entries)
            {
                string n = en.FullName.Replace('\\', '/');
                if (n.Equals(prefixed, StringComparison.OrdinalIgnoreCase)) return en;
            }
            foreach (ZipArchiveEntry en in ar.Entries)
            {
                string n = en.FullName.Replace('\\', '/');
                if (n.Equals(bare, StringComparison.OrdinalIgnoreCase)) return en;
            }
            return null;
        }
    }

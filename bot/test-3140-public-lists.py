def yes(what, cond):
    if not cond:
        FAIL.append(what)
    print(('PASS  ' if cond else 'FAIL  ') + what)


EM = chr(0x2014)


def issue(num, lanes, state='open', reason=None, updated='u1', closed=None):
    return {'number': num, 'title': 'Issue %d' % num, 'state': state,
            'state_reason': reason, 'updated_at': updated, 'closed_at': closed,
            'labels': [{'name': 'roadmap: %s' % l} for l in lanes]}


class Board:
    """A stand-in for GitHub: issues by number, comments by number, and a
       count of comment reads."""

    def __init__(self):
        self.issues, self.comments, self.reads = {}, {}, []

    def get(self, url):
        q = urllib.parse.urlparse(url)
        args = dict(urllib.parse.parse_qsl(q.query))
        if q.path.endswith('/comments'):
            num = int(q.path.split('/')[-2])
            self.reads.append(num)
            return [{'body': b, 'created_at': 't%d' % i, 'html_url': 'c'}
                    for i, b in enumerate(self.comments.get(num, []))] if args.get('page') == '1' else []
        if q.path.endswith('/issues'):
            if args.get('page') != '1':
                return []
            want = args['labels'].lower()
            return [i for i in self.issues.values()
                    if (i['state'] == 'open') == (args['state'] == 'open')
                    and want in [l['name'] for l in i['labels']]]
        raise AssertionError('unexpected read: ' + url)


said = []


def say(num, text):
    said.append((num, text))


def lane(rm, name):
    return [l for l in rm['lanes'] if l['name'] == name][0]['rows']



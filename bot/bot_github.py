def _labels(issue):
    return [str((l or {}).get('name') if isinstance(l, dict) else l)
            for l in (issue.get('labels') or [])]


def issue_tags_found(issue):
    names = _labels(issue)
    return any(l in names for l in KNOWN_LABELS)

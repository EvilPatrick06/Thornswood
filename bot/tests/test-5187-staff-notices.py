"""
test-5187-staff-notices.py

Staff notices from the board (#5187): an issue labelled "notice: staff" is
said in #staff-updates by the bot, then commented on and closed, and the
label "notice: take back" takes it out again (bot.staff_notices_once).

It holds:
  - a notice from the team is said once, as "[sender] text", with the footer
    off; the message is saved before the comment and the close;
  - the sender is the word in Say-Staff.ps1's title, else the author;
  - a failed comment or close is tried again next pass without saying the
    notice twice, and a step done is not done again;
  - a notice the send could not say stays open and the ones after it wait;
  - an author not on the team, an empty body, a body over 1800 characters
    and an issue a day old are refused with one comment, again only when
    the reasons change, and said once fixed;
  - a team App (user type Bot) may file one;
  - 30 an hour for each sender, the 31st waits;
  - take back: a said one is deleted, one not said is withheld and closed
    not planned, one that is no notice is said to be unknown; each once;
  - a list asked again with its ETag gives the kept answer on a 304;
  - the loop is started with the others.

The real bot module is imported. Never connects to anything.
"""
import os
import sys
# bot\, the folder above: the bot's tests sit in bot\tests (#5341), and

import harness_bot  # noqa: E402

bot = harness_bot.whole()
FAIL = []
NOW = 1_800_000_000


def yes(what, cond):
    if not cond:
        FAIL.append(what)
    print(('PASS  ' if cond else 'FAIL  ') + what)


def stamp(t):
    return time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(t))


def issue(num, body='Restarting the dev server at 4:30 PM.', title='Staff notice from claude',
          assoc='MEMBER', login='EvilPatrick06', kind='User', made=None):
    return {'number': num, 'title': title, 'body': body, 'author_association': assoc,
            'user': {'login': login, 'type': kind},
            'created_at': stamp(NOW - 60 if made is None else made)}


class Msg:
    def __init__(self, i):
        self.id = i


class World:
    """The staff channel and GitHub, written down."""

    def __init__(self):
        self.sent, self.deleted, self.comments, self.closed, self.saves = [], [], [], [], []
        self.send_ok = True
        self.fail_comment = self.fail_close = False
        self.gone = set()

    async def send(self, text):
        if not self.send_ok:
            return None
        self.sent.append(text)
        return Msg(1000 + len(self.sent))

    async def delete(self, mid):
        self.deleted.append(mid)
        return 'gone' if mid in self.gone else 'deleted'

    def comment(self, num, text):
        if self.fail_comment:
            raise RuntimeError('comment refused')
        self.comments.append((num, text))

    def close(self, num, reason):
        if self.fail_close:
            raise RuntimeError('close refused')
        self.closed.append((num, reason))

    def save(self, state):
        # What was saved at that moment, to check the order.
        self.saves.append((len(self.comments), len(self.closed),
                           sorted((state.get('said') or {}).keys())))


def run(state, w, notices, backs=None, now=NOW):
    return asyncio.run(bot.staff_notices_once(
        state, notices, backs or {}, w.send, w.delete, w.comment, w.close, w.save, now=now))


# ---- said once, saved first ------------------------------------------------
state, w = {}, World()
body = 'Restarting the dev server at 4:30 PM.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'
said, back, refused = run(state, w, {7: issue(7, body)})
yes('a team notice is said', said == [7] and w.sent == ['[claude] Restarting the dev server at 4:30 PM.'])
yes('the footer is not in it', 'Generated' not in w.sent[0])
yes('the message is saved before the comment and the close',
    w.saves and w.saves[0] == (0, 0, ['7']))
yes('then it is commented on and closed completed',
    len(w.comments) == 1 and 'Said in #staff-updates' in w.comments[0][1] and w.closed == [(7, 'completed')])
yes('the record holds the message', state['said']['7']['message'] == 1001 and state['said']['7']['closed'])
run(state, w, {7: issue(7, body)})
yes('a second pass says nothing again', len(w.sent) == 1 and len(w.comments) == 1 and len(w.closed) == 1)

# ---- the sender ------------------------------------------------------------
yes('the sender is the title\'s word', bot.notice_sender(issue(1, title='Staff notice from Djinn')) == 'djinn')
yes('else the author, without [bot]',
    bot.notice_sender(issue(1, title='Dev restart', login='thornswood-bramble[bot]')) == 'thornswood-bramble')

# ---- a failed comment or close ---------------------------------------------
state, w = {}, World()
w.fail_close = True
try:
    run(state, w, {8: issue(8)})
    raised = False
except RuntimeError:
    raised = True
yes('a failed close fails the pass after the notice is saved', raised and '8' in state['said'] and len(w.sent) == 1)
w.fail_close = False
run(state, w, {8: issue(8)})
yes('next pass closes it, without saying or commenting again',
    len(w.sent) == 1 and len(w.comments) == 1 and w.closed == [(8, 'completed')])

state, w = {}, World()
w.fail_comment = True
try:
    run(state, w, {9: issue(9)})
except RuntimeError:
    pass
w.fail_comment = False
run(state, w, {9: issue(9)})
yes('a failed comment is made next pass, once, and then it is closed',
    len(w.sent) == 1 and len(w.comments) == 1 and w.closed == [(9, 'completed')])

# ---- a send that fails -----------------------------------------------------
state, w = {}, World()
w.send_ok = False
said, _b, _r = run(state, w, {10: issue(10), 11: issue(11)})
yes('a notice not said stays open and the rest wait', said == [] and not w.comments and not w.closed
    and not state['said'])
w.send_ok = True
said, _b, _r = run(state, w, {10: issue(10), 11: issue(11)})
yes('then they go in order', said == [10, 11])

# ---- refusals --------------------------------------------------------------
cases = [
    ('an author not on the team', issue(20, assoc='NONE', login='stranger'), 'not on the team'),
    ('an empty body', issue(21, body='\n---\n'), 'no body'),
    ('a body over 1800 characters', issue(22, body='x' * 1801), '1801 characters'),
    ('an issue a day old', issue(23, made=NOW - 25 * 3600), 'a day ago'),
]
for what, iss, word in cases:
    state, w = {}, World()
    said, _b, refused = run(state, w, {iss['number']: iss})
    yes('%s is refused with one comment' % what,
        said == [] and refused == [iss['number']] and not w.sent and len(w.comments) == 1
        and word in w.comments[0][1] and not w.closed)
    run(state, w, {iss['number']: iss})
    yes('%s: not commented on again' % what, len(w.comments) == 1)

state, w = {}, World()
run(state, w, {22: issue(22, body='x' * 1801)})
run(state, w, {22: issue(22, body='y' * 1900)})
yes('a refusal is commented again when the reason changes', len(w.comments) == 2)
run(state, w, {22: issue(22, body='Fixed.')})
yes('and said once it is fixed', w.sent == ['[claude] Fixed.'] and '22' not in state['refused'])

state, w = {}, World()
said, _b, _r = run(state, w, {24: issue(24, title='Dev restart', assoc='NONE',
                                        login='thornswood-bramble[bot]', kind='Bot')})
yes('one of the Apps may file one', said == [24] and w.sent == ['[thornswood-bramble] Restarting the dev server at 4:30 PM.'])

# ---- 30 an hour ------------------------------------------------------------
state, w = {}, World()
many = dict((n, issue(n)) for n in range(100, 131))
said, _b, _r = run(state, w, many)
yes('30 an hour for a sender, the 31st waits open', len(said) == 30 and 130 not in said
    and (130, 'completed') not in w.closed)
said, _b, _r = run(state, w, {130: issue(130)}, now=NOW + 3601)
yes('and goes when the hour has room', said == [130])

# ---- take back -------------------------------------------------------------
state, w = {}, World()
run(state, w, {30: issue(30)})
_s, back, _r = run(state, w, {}, {30: issue(30)})
yes('a said notice is taken back by its message', back == [30] and w.deleted == [1001]
    and state['unsaid']['30'] == 'deleted' and 'taken out' in w.comments[-1][1])
run(state, w, {}, {30: issue(30)})
yes('once', w.deleted == [1001])

state, w = {}, World()
_s, back, _r = run(state, w, {31: issue(31)}, {31: issue(31)})
yes('one not said yet is withheld and closed not planned', back == [31] and not w.sent
    and state['unsaid']['31'] == 'withheld' and w.closed == [(31, 'not_planned')])

state, w = {}, World()
_s, back, _r = run(state, w, {}, {32: issue(32)})
yes('one that is no notice is said to be unknown', state['unsaid']['32'] == 'unknown'
    and not w.deleted and 'nothing was done' in w.comments[-1][1])

state, w = {}, World()
run(state, w, {33: issue(33)})
w.gone.add(1001)
run(state, w, {}, {33: issue(33)})
yes('a message already gone is said so', state['unsaid']['33'] == 'gone' and 'already gone' in w.comments[-1][1])

# ---- the ETag --------------------------------------------------------------
os.environ['GITHUB_TOKEN'] = 'not-a-real-token'


class Answer(io.BytesIO):
    def __init__(self, body, etag):
        super().__init__(body)
        self.headers = {'ETag': etag}


asked = []


def opener(req, timeout=None):
    asked.append(req.get_header('If-none-match'))
    if len(asked) == 1:
        return Answer(b'[{"number": 5}]', '"abc"')
    raise urllib.error.HTTPError(req.full_url, 304, 'Not Modified', {}, None)


cache = {}
first = bot._github_get_cached('https://api.example/x', cache, opener)
again = bot._github_get_cached('https://api.example/x', cache, opener)
yes('a list is asked again with its ETag and a 304 gives the kept answer',
    asked == [None, '"abc"'] and first == again == [{'number': 5}])

# ---- started ---------------------------------------------------------------
src = harness_bot.source()

for foot in ('\n---\nmore', '\n_Generated by [Claude Code](x)_', '\n\U0001f916 Generated with Claude Code'):
    for ch, srv in (('dev', 'Dev'), ('main', 'Main'), ('known', None)):
        yes('Footer refused in %s: %r' % (ch, foot[:12]),
            has(P(ch, 'Fine title', (DEV_OK if ch == 'dev' else MAIN_OK) + foot,
                  server=srv, issue={'state': 'open'}), 'Footer'))


import bot  # noqa: E402

FAIL = []


def yes(what, cond):
    if not cond:
        FAIL.append(what)
    print(('PASS  ' if cond else 'FAIL  ') + what)


def has(problems, word):
    return any(p.startswith(word) for p in problems)


P = bot.post_problems
DEV_OK = ('1. Join dev with the dev launcher and type /spawn wolf in chat.\n'
          '2. Watch the wolf.\nWhat should happen: a wolf appears.')
MAIN_OK = ('1. Go to the forge outside Whiterun.\n2. Make an iron dagger.\n'
           'What should happen: you get one dagger.')

yes('a good dev test task passes', P('dev', 'Spawned wolf answers', DEV_OK, server='Dev') == [])
yes('a good main test task passes',
    P('main', 'Forge makes a dagger', MAIN_OK, server='Main', fix_in_main=True) == [])
yes('a known issue with a plain line passes',
    P('known', 'Doors stick', 'Known on Dev.', issue={'state': 'open'}) == [])


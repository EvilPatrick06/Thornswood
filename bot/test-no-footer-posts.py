"""
test-no-footer-posts.py

Patrick's rule of 22 Oct: no #test-tasks, #dev-test-tasks or #known-issues
post ends with a "---" line and a "Generated by/with Claude Code" line. The
server writing a Claude session's GitHub comments puts that footer under each
one; the bot cuts it, in every form it comes in, wherever it builds a post.

The real bot module is imported. Never connects to anything.
"""
import _pyguard  # noqa: F401  (first: Python 3.11 or newer, #2276)
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
os.environ.setdefault('DISCORD_TOKEN', 'not-a-real-token')
os.environ.pop('GITHUB_TOKEN', None)

import bot  # noqa: E402

FAIL = []


def yes(what, cond):
    if not cond:
        FAIL.append(what)
    print(('PASS  ' if cond else 'FAIL  ') + what)


FOOTERS = [
    '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n',
    '\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01X)_',
    '\n\n---\nGenerated with Claude Code',
    '\n\n---\n\n\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)\n',
    '\n---\n*Generated by Claude Code*',
    '\n\n---\n',
    '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n\n---\n',
]
ISSUE = {'number': 7, 'title': 'Doors stick', 'state': 'closed',
         'html_url': 'https://github.com/EvilPatrick06/Thornswood/issues/7',
         'labels': [{'name': 'Main Findings'}]}
BODY = 'Open the door twice.\nIt should open both times.'


def ends_clean(text):
    last = text.rstrip().split('\n')[-1]
    return (not last.strip().startswith('---') and 'Generated' not in last
            and '\U0001f916' not in last)


for i, foot in enumerate(FOOTERS):
    yes('strip_footer cuts footer form %d' % i, bot.strip_footer(BODY + foot) == BODY)
    main = [{'body': 'Test task: Doors\n' + BODY + foot, 'created_at': '2026-10-22T00:00:00Z'}]
    got = bot.task_post_of(ISSUE, main)
    yes('#test-tasks post has no footer (form %d)' % i, got and got[1] == BODY)
    known = [{'body': 'Known issue: Doors\n' + BODY + foot}]
    got = bot.known_of(ISSUE, known)
    yes('#known-issues post has no footer (form %d)' % i, got[1] == BODY)
    dev = [{'body': 'Test task: Doors\nServer: Dev\n' + BODY + foot,
            'created_at': '2026-10-22T00:00:00Z', 'html_url': 'u'}]
    task = bot.dev_task_of(ISSUE, dev, '2026-10-01')
    got = bot.dev_render(ISSUE, task)
    yes('#dev-test-tasks post has no footer (form %d)' % i,
        ends_clean(got[1]) and got[1].endswith(BODY))

yes('a rule inside the text is kept',
    bot.strip_footer('a\n---\nb') == 'a\n---\nb')
yes('a line about generating something, not a footer, is kept',
    bot.strip_footer('Check the map.\nGenerated by the world seed.')
    == 'Check the map.\nGenerated by the world seed.')
yes('a footer-only test task falls back to the plain body',
    bot.task_post_of(ISSUE, [{'body': 'Test task: Doors\n---\nGenerated with Claude Code'}])[1]
    == 'Check this on main.')

print('\n%s' % ('ALL PASS' if not FAIL else '%d FAILED' % len(FAIL)))
sys.exit(1 if FAIL else 0)

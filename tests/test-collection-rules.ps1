<#
  test-collection-rules.ps1

      pwsh -NoProfile -File .\tests\test-collection-rules.ps1

  Check-CollectionRules.ps1, which reads the plugin rules the Nexus collection
  carries against a plugin list. Entry 274 on the To Do List.

  WHY. Revision 5 of the collection pins the 52 full plugins in one chain of
  "load after" rules, and LOOT will not swap two of them. The entry's trap is
  what happens next: "A PLUGIN ADDED LATER IS NOT PINNED UNTIL SOMEBODY GIVES
  IT A RULE. ... Forget that and the new plugin floats, which is the same load
  order mismatch this entry exists to stop, arriving one revision later with
  nobody connecting the two." The check is what connects them, so these prove
  it says NO to each way the chain can stop holding, and nothing else.

  The case measured on 24 September is here by name: the reference list on
  Patrick's machine had Thornswood-Content.esp moved from line 31 to the end,
  which breaks "Populated Cities Towns Villages Legendary.esp loads after
  Thornswood-Content.esp".

  Everything is built under its own temp folder: collections, plugin lists,
  and plugin files with real TES4 headers, since light plugins are told from
  full ones by the ESL flag. APPDATA is pointed there for the runs that find
  the collection the way Vortex lays it out. The real script runs as a child
  process, so what is under test is what ships. The last check proves it
  wrote nothing.
#>
[CmdletBinding()]
param([string]$CheckPath)

$ErrorActionPreference = 'Stop'
$Here = $PSScriptRoot
if (-not $Here) { $Here = Split-Path -Parent $MyInvocation.MyCommand.Definition }
# The tests are in tests\, what they test is in tools\.
$Here = Join-Path (Split-Path -Parent $Here) 'tools'
if (-not $CheckPath) { $CheckPath = Join-Path $Here 'Check-CollectionRules.ps1' }

$script:pass = 0
$script:fail = 0
function Yes([string]$what, [bool]$cond) {
    if ($cond) { $script:pass++; Write-Host "PASS  $what" }
    else { $script:fail++; Write-Host "FAIL  $what" }
}
function Finish {
    Write-Host ''
    Write-Host ("{0} passed, {1} failed" -f $script:pass, $script:fail)
    if ($script:fail) { exit 1 }
    exit 0
}

Yes 'Check-CollectionRules.ps1 exists' (Test-Path -LiteralPath $CheckPath)
if (-not (Test-Path -LiteralPath $CheckPath)) { Finish }

$root = Join-Path ([IO.Path]::GetTempPath()) ('thornswood-rules-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
$realAppData = $env:APPDATA
$shell = (Get-Process -Id $PID).Path

# ---- fixture builders --------------------------------------------------------

# A plugin file with a TES4 header: the four letters, the record size, then the
# flags, 0x1 a master and 0x200 the ESL flag that makes it light.
function Plugin([string]$dir, [string]$name, [uint32]$flags) {
    $b = New-Object byte[] 24
    [Text.Encoding]::ASCII.GetBytes('TES4').CopyTo($b, 0)
    [BitConverter]::GetBytes([uint32]0).CopyTo($b, 4)
    [BitConverter]::GetBytes($flags).CopyTo($b, 8)
    [IO.File]::WriteAllBytes((Join-Path $dir $name), $b)
}

# A plugin list the way Vortex writes one: a comment first, CRLF, no BOM.
function PluginList([string]$path, [string[]]$lines) {
    $null = New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path)
    $text = (@('# Automatically generated by Vortex') + $lines) -join "`r`n"
    [IO.File]::WriteAllText($path, $text + "`r`n", (New-Object Text.UTF8Encoding($false)))
}

# A collection.json. Each rule is a hashtable with name and after or before,
# names in lower case, as Vortex writes them. $null for a collection that
# carries no plugin rules at all, which is revisions 2 to 4.
function Collection([string]$path, $rules) {
    $null = New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path)
    $doc = [ordered]@{ info = [ordered]@{ name = 'Thornswood' }; mods = @() }
    if ($null -ne $rules) { $doc.pluginRules = [ordered]@{ plugins = @($rules); groups = @() } }
    [IO.File]::WriteAllText($path, ($doc | ConvertTo-Json -Depth 8), (New-Object Text.UTF8Encoding($false)))
}

function Run([string[]]$argList) {
    # Local to this call: under Windows PowerShell 5.1 a child writing to
    # stderr through 2>&1 is a terminating error when this is Stop.
    $ErrorActionPreference = 'Continue'
    $all = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $CheckPath) + $argList
    $out = & $shell @all 2>&1 | Out-String
    return [pscustomobject]@{ Code = $LASTEXITCODE; Out = $out }
}
function Has([string]$text, [string]$part) { return ($text.IndexOf($part, [StringComparison]::Ordinal) -ge 0) }

try {
    $data = Join-Path $root 'Data'
    $null = New-Item -ItemType Directory -Force -Path $data

    # The real names, a slice of revision 5's chain.
    Plugin $data 'Water for ENB.esm' 0x1
    Plugin $data 'Embers XD.esm' 0x1
    Plugin $data 'RaceCompatibility.esm' 0x1
    Plugin $data 'SkyUI_SE.esp' 0x200
    Plugin $data 'LSFX-SSE-Audiosettings.esp' 0
    Plugin $data 'I4IconAddon.esp' 0x200
    Plugin $data 'aaaGraniteHill.esp' 0
    Plugin $data 'Thornswood-Content.esp' 0
    Plugin $data 'Populated Cities Towns Villages Legendary.esp' 0
    Plugin $data 'SkyrimSewers.esp' 0
    Plugin $data 'Playable Rieklings.esp' 0
    Plugin $data 'New Plugin.esp' 0
    Plugin $data 'New Light.esp' 0x200
    Plugin $data 'Alpha.esp' 0
    Plugin $data 'Beta.esp' 0
    Plugin $data 'Gamma.esp' 0
    Plugin $data 'LightMid.esp' 0x200

    # Revision 5's shape: one chain, lsfx after two plugins as the real one
    # is, and one rule naming a base master, which the game puts first
    # whatever any list says and no plugin list enables.
    $chain = @(
        @{ name = 'water for enb.esm'; after = @('skyrim.esm') },
        @{ name = 'embers xd.esm'; after = @('water for enb.esm') },
        @{ name = 'lsfx-sse-audiosettings.esp'; after = @('embers xd.esm', 'racecompatibility.esm') },
        @{ name = 'aaagranitehill.esp'; after = @('lsfx-sse-audiosettings.esp') },
        @{ name = 'thornswood-content.esp'; after = @('aaagranitehill.esp') },
        @{ name = 'populated cities towns villages legendary.esp'; after = @('thornswood-content.esp') },
        @{ name = 'skyrimsewers.esp'; after = @('populated cities towns villages legendary.esp') },
        @{ name = 'racecompatibility.esm'; after = @('embers xd.esm') },
        @{ name = 'playable rieklings.esp'; after = @('skyrimsewers.esp') }
    )
    $col5 = Join-Path $root 'col5\collection.json'
    Collection $col5 $chain

    # The server's order: the light plugins sit anywhere, a disabled line is
    # ignored, the case is not the collection's.
    $server = @(
        '*Water for ENB.esm', '*Embers XD.esm', '*RaceCompatibility.esm', '*TrueHUD.esl', '*SkyUI_SE.esp',
        '*LSFX-SSE-Audiosettings.esp', '*I4IconAddon.esp', '*aaaGraniteHill.esp', '*Thornswood-Content.esp',
        '*Populated Cities Towns Villages Legendary.esp', '*SkyrimSewers.esp', '*Playable Rieklings.esp',
        'Disabled Thing.esp'
    )
    $good = Join-Path $root 'lists\good.txt'
    PluginList $good $server

    # What the reference on Patrick's machine became at 22:39 on 23 September.
    $tonight = Join-Path $root 'lists\content-at-the-end.txt'
    PluginList $tonight (@($server | Where-Object { $_ -ne '*Thornswood-Content.esp' }) + '*Thornswood-Content.esp')

    $newFull = Join-Path $root 'lists\new-full.txt'
    PluginList $newFull ($server + '*New Plugin.esp')
    $newLight = Join-Path $root 'lists\new-light.txt'
    PluginList $newLight ($server + '*New Light.esp')
    $newEsl = Join-Path $root 'lists\new-esl.txt'
    PluginList $newEsl ($server + '*New Thing.esl')
    $noSewers = Join-Path $root 'lists\no-sewers.txt'
    PluginList $noSewers @($server | Where-Object { $_ -ne '*SkyrimSewers.esp' })
    $ghost = Join-Path $root 'lists\ghost.txt'
    PluginList $ghost ($server + '*Ghost.esp')

    $noRules = Join-Path $root 'col-none\collection.json'
    Collection $noRules $null

    # Two plugins both after the same one, and nothing between them.
    $siblings = Join-Path $root 'col-siblings\collection.json'
    Collection $siblings @(
        @{ name = 'beta.esp'; after = @('alpha.esp') },
        @{ name = 'gamma.esp'; after = @('alpha.esp') }
    )
    $abg = Join-Path $root 'lists\abg.txt'
    PluginList $abg @('*Alpha.esp', '*Beta.esp', '*Gamma.esp')

    # A chain through a light plugin.
    $throughLight = Join-Path $root 'col-light\collection.json'
    Collection $throughLight @(
        @{ name = 'lightmid.esp'; after = @('alpha.esp') },
        @{ name = 'beta.esp'; after = @('lightmid.esp') }
    )
    $withMid = Join-Path $root 'lists\with-mid.txt'
    PluginList $withMid @('*Alpha.esp', '*LightMid.esp', '*Beta.esp')
    $withoutMid = Join-Path $root 'lists\without-mid.txt'
    PluginList $withoutMid @('*Alpha.esp', '*Beta.esp')

    # "before" rules, which Vortex's format allows though revision 5 has none.
    $beforeCol = Join-Path $root 'col-before\collection.json'
    Collection $beforeCol @( @{ name = 'alpha.esp'; before = @('beta.esp') } )
    $ab = Join-Path $root 'lists\ab.txt'
    PluginList $ab @('*Alpha.esp', '*Beta.esp')
    $ba = Join-Path $root 'lists\ba.txt'
    PluginList $ba @('*Beta.esp', '*Alpha.esp')

    # A machine: Vortex's staging folder with two revisions of ours and a
    # newer one of somebody else's, and a Thornswood root with the reference.
    $appData = Join-Path $root 'AppData'
    $mods = Join-Path $appData 'Vortex\skyrimse\mods'
    Collection (Join-Path $mods 'collection_ombo2a_4_2026-09-20T10-00-00Z\collection.json') $null
    Collection (Join-Path $mods 'collection_ombo2a_5_2026-09-22T22-26-11Z\collection.json') $chain
    Collection (Join-Path $mods 'collection_other1_9_2026-09-23T10-00-00Z\collection.json') $null
    $machine = Join-Path $root 'Thornswood'
    PluginList (Join-Path $machine 'Profile\Default\plugins.txt') $server
    $null = New-Item -ItemType Directory -Force -Path (Join-Path $machine 'Game')
    Copy-Item -LiteralPath $data -Destination (Join-Path $machine 'Game\Data') -Recurse
    $machineOther = Join-Path $root 'ThornswoodOther'
    PluginList (Join-Path $machineOther 'Profile\Default\plugins.txt') $server
    $null = New-Item -ItemType Directory -Force -Path (Join-Path $machineOther 'Game')
    Copy-Item -LiteralPath $data -Destination (Join-Path $machineOther 'Game\Data') -Recurse
    [IO.File]::WriteAllText((Join-Path $machineOther 'config.json'),
        '{ "CollectionUrl": "https://www.nexusmods.com/games/skyrimspecialedition/collections/other1" }',
        (New-Object Text.UTF8Encoding($false)))
    $emptyAppData = Join-Path $root 'EmptyAppData'
    $null = New-Item -ItemType Directory -Force -Path $emptyAppData

    # Everything the runs may read, so the last check can prove none was written.
    # Every path, and every file's size and write time. Not a folder's write
    # time: measured on the first run of this harness, NTFS moved the times of
    # folders made a moment earlier by 1 to 80 milliseconds after the fixture
    # was written, with every file in them unchanged. A file added, removed or
    # rewritten still shows.
    function Snapshot {
        return (@(Get-ChildItem -LiteralPath $root -Recurse -Force | Sort-Object FullName | ForEach-Object {
            if ($_.PSIsContainer) { $_.FullName + '|dir' }
            else { $_.FullName + '|' + $_.Length + '|' + $_.LastWriteTimeUtc.Ticks }
        }) -join "`n")
    }
    $before = Snapshot

    # ---- the list that holds ---------------------------------------------------
    $r = Run @('-Collection', $col5, '-List', $good, '-Data', $data)
    Yes 'the server''s order passes (exit 0)' ($r.Code -eq 0)
    Yes 'and says HELD' ((Has $r.Out '  HELD. A clean install') -and -not (Has $r.Out 'NOT HELD'))
    Yes 'and counts 9 full plugins, the light ones and the disabled line left out' (Has $r.Out '12 enabled, 9 full, 3 light')
    Yes 'and names where the chain ends, for the next plugin''s rule' (Has $r.Out 'The chain ends at Playable Rieklings.esp')
    Yes 'a rule naming a base master is not a plugin the list lacks' (-not (Has $r.Out 'skyrim.esm: a rule names it'))

    # ---- what it has to catch ------------------------------------------------
    $r = Run @('-Collection', $col5, '-List', $tonight, '-Data', $data)
    Yes 'Thornswood-Content.esp at the end fails (exit 1)' ($r.Code -eq 1)
    Yes 'and names the rule it breaks, with both lines' `
        (Has $r.Out 'Populated Cities Towns Villages Legendary.esp (line 10) must load after Thornswood-Content.esp (line 14)')
    Yes 'and says the rules put the last pair the other way round' `
        (Has $r.Out 'Playable Rieklings.esp (line 12) then Thornswood-Content.esp (line 14): the rules put them the other way round.')

    $r = Run @('-Collection', $col5, '-List', $newFull, '-Data', $data)
    Yes 'a full plugin added with no rule fails (exit 1)' ($r.Code -eq 1)
    Yes 'and says it floats and which rule the next upload needs' `
        (Has $r.Out 'New Plugin.esp (line 15): no rule names it, so LOOT may put it anywhere. The next upload needs a rule loading it after Playable Rieklings.esp.')

    $r = Run @('-Collection', $col5, '-List', $newLight, '-Data', $data)
    Yes 'a plugin carrying the ESL flag needs no rule (exit 0)' ($r.Code -eq 0)
    $r = Run @('-Collection', $col5, '-List', $newEsl, '-Data', $data)
    Yes 'an .esl needs no rule (exit 0)' ($r.Code -eq 0)

    $r = Run @('-Collection', $noRules, '-List', $good, '-Data', $data)
    Yes 'a collection with no plugin rules, revisions 2 to 4, fails (exit 1)' ($r.Code -eq 1)
    Yes 'and says there are none' (Has $r.Out 'none at all')

    $r = Run @('-Collection', $siblings, '-List', $abg, '-Data', $data)
    Yes 'two plugins both named but not ordered against each other fail (exit 1)' ($r.Code -eq 1)
    Yes 'and the pair is named' (Has $r.Out 'Beta.esp (line 3) then Gamma.esp (line 4): no rule orders the two, so LOOT may swap them.')

    $r = Run @('-Collection', $throughLight, '-List', $withMid, '-Data', $data)
    Yes 'a chain through an enabled light plugin holds (exit 0)' ($r.Code -eq 0)
    $r = Run @('-Collection', $throughLight, '-List', $withoutMid, '-Data', $data)
    Yes 'the same chain with the light plugin not installed holds nothing (exit 1)' ($r.Code -eq 1)
    Yes 'and the light plugin itself is not reported as missing' (-not (Has $r.Out 'lightmid.esp: a rule names it'))

    $r = Run @('-Collection', $col5, '-List', $noSewers, '-Data', $data)
    Yes 'a full plugin a rule names that the list lacks fails (exit 1)' ($r.Code -eq 1)
    Yes 'and is named' (Has $r.Out 'skyrimsewers.esp: a rule names it and the list does not enable it.')

    $r = Run @('-Collection', $beforeCol, '-List', $ab, '-Data', $data)
    Yes 'a "before" rule is read and holds (exit 0)' ($r.Code -eq 0)
    $r = Run @('-Collection', $beforeCol, '-List', $ba, '-Data', $data)
    Yes 'and a list that breaks it fails (exit 1)' ($r.Code -eq 1)

    $r = Run @('-Collection', $col5, '-List', $ghost, '-Data', $data)
    Yes 'an enabled plugin that is not in Data is said so' (Has $r.Out 'not in the Data folder and are counted as full: Ghost.esp')
    Yes 'and, with no rule, fails (exit 1)' ($r.Code -eq 1)

    $r = Run @('-Collection', (Split-Path -Parent $col5), '-List', $good, '-Data', $data)
    Yes 'the collection''s folder works as well as its collection.json (exit 0)' ($r.Code -eq 0)

    $r = Run @('-Collection', $col5, '-List', (Join-Path $root 'lists\no-such.txt'), '-Data', $data)
    Yes 'a list that is not there stops it (exit 1)' ($r.Code -eq 1 -and (Has $r.Out 'no plugin list at'))
    $r = Run @('-Collection', $col5, '-List', $good, '-Data', (Join-Path $root 'no-such-data'))
    Yes 'a Data folder that is not there stops it (exit 1)' ($r.Code -eq 1 -and (Has $r.Out 'no Data folder at'))

    # ---- finding the collection the way Vortex lays it out ----------------------
    try {
        $env:APPDATA = $appData
        $r = Run @('-Root', $machine)
        Yes 'with no config.json, the launcher''s own collection is read, its newest revision (exit 0)' ($r.Code -eq 0)
        Yes 'and it says revision 5' (Has $r.Out 'revision 5,')
        Yes 'from revision 5''s folder, not revision 4''s' (Has $r.Out 'collection_ombo2a_5_2026-09-22T22-26-11Z')
        Yes 'and the reference under Profile\Default is the list it checked' (Has $r.Out (Join-Path $machine 'Profile\Default\plugins.txt'))

        $r = Run @('-Root', $machineOther)
        Yes 'config.json names the collection: it reads that one''s revision 9' (Has $r.Out 'revision 9,')
        Yes 'which carries no rules, so it fails (exit 1)' ($r.Code -eq 1)

        $env:APPDATA = $emptyAppData
        $r = Run @('-Root', $machine)
        Yes 'with no Vortex here it says SKIP' (Has $r.Out 'SKIP')
        Yes 'and exits 0, so a machine without Vortex can run it' ($r.Code -eq 0)
    } finally {
        $env:APPDATA = $realAppData
    }

    # ---- read only ---------------------------------------------------------------
    $after = Snapshot
    Yes 'nothing it read was written, moved or added to' ($after -eq $before)
    if ($after -ne $before) {
        Compare-Object ($before -split "`n") ($after -split "`n") | ForEach-Object { Write-Host ('      ' + $_.SideIndicator + ' ' + $_.InputObject) }
    }
}
finally {
    $env:APPDATA = $realAppData
    Remove-Item -LiteralPath $root -Recurse -Force -EA SilentlyContinue
}

Finish

'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const pop = JSON.parse(fs.readFileSync(path.join(root, 'game/data/npc-population.json'), 'utf8'));
const doc = JSON.parse(fs.readFileSync(path.join(root, 'game/data/merchant-traders.json'), 'utf8'));
const traders = pop.npcs.filter(function (n) { return n.role === 'trader' && n.keep; });
assert.equal(traders.length, 60);
assert.equal(doc.count, 60);
assert.equal(Object.keys(doc.byRef).length, 60);
const refs = new Set(traders.map(function (n) { return n.ref; }));
for (const ref of Object.keys(doc.byRef)) assert.equal(refs.has(ref), true);
let unpriced = 0;
for (const row of Object.values(doc.byRef)) if (!row.bookHold) unpriced += 1;
assert.equal(unpriced, 0);
assert.equal(doc.byRef['fe498:Skyrim.esm'], undefined, 'extra military traders are retired');
assert.equal(doc.byRef['fe4cb:Skyrim.esm'], undefined);
const page = fs.readFileSync(path.join(root, 'docs/systems/merchant-traders.md'), 'utf8');
assert.match(page, /Total: 60/);
const src = fs.readFileSync(path.join(root, 'game/merchant-trading.js'), 'utf8');
assert.equal(src.includes('addItem'), false);
assert.doesNotMatch(src, /\.set\([^\n]*['"]inventory['"]/);
assert.match(src, /compareAndSetInventory\(id, expected, receipt, next, sequence, profile\)/);
assert.match(src, /getSavedInventoryReceipt/);
const mode = fs.readFileSync(path.join(root, 'game/gamemode.js'), 'utf8');
assert.match(mode, /installMerchantTrading/);
assert.match(mode, /native transfer absent/);
assert.match(mode, /word === '\/merchant'/);
assert.match(mode, /merchants\.activate/);
const front = fs.readFileSync(path.join(root, 'game/plugins/thornswood-front.js'), 'utf8');
assert.match(front, /function merchantPress/);
assert.match(front, /\/merchant e /);
const sites = JSON.parse(fs.readFileSync(path.join(root, 'game/data/guild-sites.json'), 'utf8'));
assert.equal(sites.sites.length, 10);
assert.equal(page.includes('| no hold |'), false);
console.log('PASS 60 trader places and the native transfer gate');

'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {createRequire}=require('node:module');
const {createSettlement}=require('../game/merchant-settlement');
const copy=value=>JSON.parse(JSON.stringify(value));
const source=fs.readFileSync(path.join(__dirname,'../game/gamemode.js'),'utf8');
const ctx={Map,Set,Number,JSON,require};
vm.createContext(ctx);vm.runInContext(source.slice(source.indexOf('// NPC MERCHANT PURSES BEGIN'),source.indexOf('// NPC MERCHANT PURSES END')),ctx);
const settlementTest=path.join(__dirname,'test-merchant-settlement.js');
const fixtureSource=fs.readFileSync(settlementTest,'utf8');
const fixtureContext={Map,Set,JSON,require:createRequire(settlementTest)};
vm.createContext(fixtureContext);vm.runInContext(fixtureSource.slice(0,fixtureSource.indexOf('// Four large')),fixtureContext);
const human=fixtureContext.fixture();
let ledger={version:2,entries:{'1:Skyrim.esm':{version:1,reference:'1:Skyrim.esm',base:'a:Skyrim.esm',revision:0,purse:250,stock:[],supply:{}},'2:Skyrim.esm':null}};
const projections=new Map(),present=new Set([1,2]);let retiredReads=0;
const api={makeProperty(){},getIdFromDesc:ref=>({'1:Skyrim.esm':1,'2:Skyrim.esm':2}[ref]),
  getNpcAIState(id){if(!present.has(id)){retiredReads++;throw Error('retired actor absent');}return {isHuman:false,profileId:0};},
  get(id,key){if(!present.has(id)){retiredReads++;throw Error('retired actor absent');}return key==='baseDesc'?'a:Skyrim.esm':projections.get(id);},
  set(id,key,value){assert.ok(present.has(id),'retired actor cannot receive a projection');projections.set(id,copy(value));}};
const history=[['1:Skyrim.esm','a:Skyrim.esm'],['2:Skyrim.esm','a:Skyrim.esm']];
const row=id=>[id+':Skyrim.esm','a:Skyrim.esm',null,null,null,null,'trader'];
const storage={durable:true,namespace:'dev:retirement',load:()=>copy(ledger),save(next){ledger=copy(next);return true;}};
const make=keep=>ctx.createNpcMerchantPurses(api,{keep,merchantHistory:history},storage);
const active=make([row(1),row(2)]);
const offer=human.offer();offer.previous=active.prepare(1);
const initial=createSettlement({purses:active,transfer:human.transfer,world:storage.namespace});
assert.equal(initial.begin(offer).accepted,true);
assert.equal(ledger.entries['1:Skyrim.esm'].pending.phase,'debit');
const reserved=copy(ledger.entries['1:Skyrim.esm']);
initial.shutdown();active.shutdown();present.delete(1);
const retired=make([row(2)]);
assert.deepEqual(retired.read(1),reserved,'the historical private state survives retirement verbatim');
assert.equal(retired.prepare(1),null,'retired identities cannot open a panel or receive a grant');
assert.equal(retired.pendingRecords().length,1,'the absent identity still reserves its human inventory');
const recovery=createSettlement({purses:retired,transfer:human.transfer,world:storage.namespace});
assert.equal(recovery.canInventoryMutation(10),false);
human.save();recovery.tick();human.save();recovery.tick();
assert.equal(retired.pendingRecords().length,0);
assert.equal(retired.read(1).purse,247);
assert.equal(retired.read(1).stock[0].entry.health,0.7);
assert.equal(human.inv.entries.find(row=>row.baseId===15).count,43,'a saved retired trade pays exactly once');
recovery.tick();assert.equal(human.inv.entries.find(row=>row.baseId===15).count,43);
assert.equal(retiredReads,0,'recovery never reads or creates the absent merchant actor');
const completed=copy(retired.read(1));
assert.throws(()=>retired.compareAndCommit(1,completed.revision,{...completed,purse:250}),/retired/i);
assert.equal(retired.prepare(2).purse,250,'only a retained null entry receives its first grant');
assert.deepEqual(retired.read(1),completed);
assert.deepEqual(make([row(2)]).read(1),completed,'restart keeps the retired balance and stock');
assert.throws(()=>ctx.createNpcMerchantPurses(api,{keep:[row(2)],merchantHistory:[history[1],history[1]]},storage),/manifest|catalogue/i);
assert.throws(()=>ctx.createNpcMerchantPurses(api,{keep:[row(2)],merchantHistory:[history[0]]},storage),/manifest|catalogue/i);
assert.throws(()=>ctx.createNpcMerchantPurses(api,{keep:[row(2)],merchantHistory:[history[0],['2:Skyrim.esm','b:Skyrim.esm']]},storage),/manifest|catalogue/i);
console.log('PASS retired merchant private state, actor-free pending recovery, receipts, metadata and active-only grants');

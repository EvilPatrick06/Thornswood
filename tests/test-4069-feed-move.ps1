<#
  test-4069-feed-move.ps1

      pwsh -NoProfile -File .\tests\test-4069-feed-move.ps1

  A release from the feed moves the collection revision (#4069). Until
  31 Oct 2026 a Ship from the feed carried the last release's plugin list and
  refused a new revision, and with One retired from releases revision 6
  stopped every Ship. This holds:
    1. Get-ShipFeedMoveRevision (CollectionRevision.ps1) moves only up to the
       recorded revision, only from a feed that names one, and only from a
       checkout with the Last plugin's recipe and manifest.
    2. New-ShipFeedMoveLists (Ship-Rules.ps1) writes the servers' order,
       game\data\last-plugin.json's, the way the last release's list is:
       its header, CRLF, no byte order mark, every name enabled but the base
       masters and what the game loads on its own (the last release's
       loadorder.txt names those), Thornswood-Last.esp on the end, and a
       loadorder.txt of the masters, those, then the list. The list it
       writes passes Get-ShipFeedOrderProblem against the server's order
       built from the same file, the repository's own included. An order
       that does not start with the base masters is refused.
    3. Ship.ps1 moves the revision before the version, runs SkyUI's check
       on the box's store of the revision with our files over it, and moves
       main only once the dev feed carries the revision.
    4. Publish-Update.ps1 moves the revision, writes the list, records its
       hashes and order key, holds it to the server as before, packs it as
       profile\plugins.txt and profile\loadorder.txt and records it as the
       golden list, and leaves "The server needs this too" to a Ship from One.
  Nothing connects anywhere, and everything it writes is in its own temp folder.
#>
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Here = $PSScriptRoot
if (-not $Here) { $Here = Split-Path -Parent $MyInvocation.MyCommand.Definition }
$repo = Split-Path -Parent $Here
$rel = Join-Path $repo 'scripts\release'

$script:pass = 0; $script:fail = 0
function Yes([string]$what, [bool]$cond) {
    if ($cond) { $script:pass++; Write-Host "PASS  $what" }
    else { $script:fail++; Write-Host "FAIL  $what" -ForegroundColor Red }
}
function Put([string]$path, [string]$content) {
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
    [IO.File]::WriteAllText($path, $content, (New-Object Text.UTF8Encoding($false)))
}
function Lines([string]$path) { return @([IO.File]::ReadAllText($path) -split "`r`n" | Where-Object { $_ -ne '' }) }

. (Join-Path $rel 'ShippedBytes.ps1')
. (Join-Path $rel 'Ship-Rules.ps1')

$T = Join-Path ([IO.Path]::GetTempPath()) ('ts-4069-move-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -ItemType Directory -Force -Path $T | Out-Null
try {
    # ---- 1. when a release from the feed moves the revision -----------------
    Write-Host 'when the feed moves'
    $rec = Join-Path $T 'records\collection-plugins.json'
    Put $rec '{"version":1,"collection":"7essxf","revision":6,"plugins":[]}'
    Put (Join-Path $T 'game\data\last-plugin.recipe') 'recipe'
    Put (Join-Path $T 'game\data\last-plugin.json') '{"loadOrder":["Skyrim.esm"]}'
    Yes 'a feed on revision 2 with the record on 6 moves to 6' ((Get-ShipFeedMoveRevision $T 2) -eq 6)
    Yes 'a feed already on the record does not move' ((Get-ShipFeedMoveRevision $T 6) -eq 0)
    Yes 'a feed ahead of the record does not move' ((Get-ShipFeedMoveRevision $T 7) -eq 0)
    Yes 'a feed that names no revision does not move' ((Get-ShipFeedMoveRevision $T 0) -eq 0)
    Remove-Item -LiteralPath (Join-Path $T 'game\data\last-plugin.recipe') -Force
    Yes 'a checkout without the Last plugin''s recipe does not move' ((Get-ShipFeedMoveRevision $T 2) -eq 0)
    Yes 'and with no record nothing moves' ((Get-ShipFeedMoveRevision (Join-Path $T 'nowhere') 2) -eq 0)

    # ---- 2. the list it carries ---------------------------------------------
    Write-Host ''; Write-Host 'the list'
    $hdr = '# Automatically generated by Vortex'
    $prevPlugins = Join-Path $T 'prev\plugins.txt'
    $prevLo = Join-Path $T 'prev\loadorder.txt'
    Put $prevPlugins ((@($hdr, '*Old.esp', 'CBBE.esp', '*Atlas.esp', '*Thornswood-Last.esp') -join "`r`n") + "`r`n")
    Put $prevLo ((@($hdr) + $ShipBaseMasters + @('ccBGSSSE001-Fish.esm', 'ccQDRSSE001-SurvivalMode.esl', '_ResourcePack.esl', 'Old.esp', 'CBBE.esp', 'Atlas.esp', 'Thornswood-Last.esp') -join "`r`n") + "`r`n")
    $order = @($ShipBaseMasters) + @('_ResourcePack.esl', 'cheddars_mashups.esl', 'Old.esp', 'CBBE.esp')
    $m = Join-Path $T 'move'
    Put (Join-Path $m 'game\data\last-plugin.json') (([ordered]@{ loadOrder = $order } | ConvertTo-Json))
    $out = Join-Path $T 'out'
    $mv = New-ShipFeedMoveLists $m $prevPlugins $prevLo $out
    $pl = Lines $mv.Plugins
    $lo = Lines $mv.LoadOrder
    Yes 'plugins.txt keeps the last release''s header' ($pl[0] -eq $hdr)
    Yes 'it enables the order''s names, less the masters and what the game loads on its own, with Last on the end' (($pl[1..($pl.Count - 1)] -join '|') -eq '*cheddars_mashups.esl|*Old.esp|*CBBE.esp|*Thornswood-Last.esp')
    Yes '  the plugin the last list had off is on when the servers load it' ($pl -contains '*CBBE.esp')
    Yes '  the plugin the revision dropped is gone' (-not @($pl | Where-Object { $_ -match 'Atlas' }).Count)
    Yes 'what the game loads on its own is read off the last loadorder.txt' (($mv.Own -join '|') -eq 'ccBGSSSE001-Fish.esm|ccQDRSSE001-SurvivalMode.esl|_ResourcePack.esl')
    Yes 'loadorder.txt is the masters, those, then the list, unstarred' (($lo -join '|') -eq ((@($hdr) + $ShipBaseMasters + $mv.Own + @('cheddars_mashups.esl', 'Old.esp', 'CBBE.esp', 'Thornswood-Last.esp')) -join '|'))
    $bytes = [IO.File]::ReadAllBytes($mv.Plugins)
    Yes 'CRLF and no byte order mark, as the last release''s' ($bytes[0] -eq [byte][char]'#' -and ([IO.File]::ReadAllText($mv.Plugins)).Contains("`r`n") -and -not ([IO.File]::ReadAllText($mv.Plugins) -match "[^`r]`n"))
    $server = @($order) + $ShipLastPlugin
    $fo = Get-ShipFeedOrderProblem $server $mv.Enabled
    Yes 'the list passes the server''s order built from the same file' ($fo.Problem -eq '' -and (@($fo.Ccc) -join '|') -eq '_ResourcePack.esl')
    $fo2 = Get-ShipFeedOrderProblem ($server | Where-Object { $_ -ne 'cheddars_mashups.esl' }) $mv.Enabled
    Yes '  and fails a server still on the old order, naming the plugin' ($fo2.Problem -match 'cheddars_mashups\.esl')

    # The repository's own order, with lists shaped as both feeds' are.
    $real = New-ShipFeedMoveLists $repo $prevPlugins $prevLo (Join-Path $T 'real')
    $realOrder = @(((Get-Content -LiteralPath (Join-Path $repo 'game\data\last-plugin.json') -Raw) | ConvertFrom-Json).loadOrder)
    $fr = Get-ShipFeedOrderProblem (@($realOrder) + $ShipLastPlugin) $real.Enabled
    Yes 'the repository''s last-plugin.json makes a list its own server order passes' ($fr.Problem -eq '' -and $real.Enabled[-1] -eq $ShipLastPlugin)
    Yes '  every plugin of the order but the masters and _ResourcePack.esl is on' ($real.Enabled.Count -eq ($realOrder.Count - $ShipBaseMasters.Count - 1 + 1))
    Yes '  and Thornswood-Last.esp was built against that list (Get-ShipLastPluginProblem)' ((Get-ShipLastPluginProblem $repo $real.Enabled @($fr.Ccc)) -eq '')

    Put (Join-Path $T 'bad\game\data\last-plugin.json') (([ordered]@{ loadOrder = @('Update.esm', 'Skyrim.esm', 'Dawnguard.esm', 'HearthFires.esm', 'Dragonborn.esm', 'A.esp') } | ConvertTo-Json))
    $threw = ''
    try { $null = New-ShipFeedMoveLists (Join-Path $T 'bad') $prevPlugins $prevLo (Join-Path $T 'badout') } catch { $threw = $_.Exception.Message }
    Yes 'an order that does not start with the base masters is refused' ($threw -match 'base masters')
    $threw = ''
    try { $null = New-ShipFeedMoveLists (Join-Path $T 'nowhere') $prevPlugins $prevLo (Join-Path $T 'badout') } catch { $threw = $_.Exception.Message }
    Yes 'a checkout with no last-plugin.json is refused' ($threw -match 'no game\\data\\last-plugin\.json')

    # ---- 3. Ship.ps1 --------------------------------------------------------
    Write-Host ''; Write-Host 'Ship.ps1'
    $ship = [IO.File]::ReadAllText((Join-Path $rel 'Ship.ps1'))
    $iMove = $ship.IndexOf('$revMove = Get-ShipFeedMoveRevision -RepoDir $RepoDir -Built $revBuilt')
    $iAsk = $ship.IndexOf('$revWhy = Get-ShipCollectionRevisionProblem -RepoDir $RepoDir -Built $revBuilt -Source "the $Channel feed''s last release"')
    $iVersion = $ship.IndexOf("Head 'Collection revision'")
    Yes 'Ship moves the revision from the feed before it asks the record' ($iMove -gt $iVersion -and $iAsk -gt $iMove)
    $iSky = $ship.IndexOf('if ($FromFeed -and $revMoveFrom) {', $ship.IndexOf("Head 'SkyUI menus'"))
    Yes 'SkyUI''s check runs on a move from the feed' ($iSky -gt 0)
    $sky = if ($iSky -gt 0) { $ship.Substring($iSky, $ship.IndexOf('} elseif ($FromFeed) {', $iSky) - $iSky) } else { '' }
    Yes '  on the box''s store of the recorded revision' ($sky.Contains('Get-ThornswoodCollectionStore -RecordPath') -and $sky.Contains('Invoke-ThornswoodCollectionFetch') -and $sky.Contains('$skyuiStore.Menus'))
    Yes '  with our files over it' ($sky.Contains('Test-ShipSkyUIInput $rel'))
    Yes '  in last-plugin.json''s order with Last on the end' ($sky.Contains("game\data\last-plugin.json") -and $sky.Contains('$skyuiOrder + $ShipLastPlugin'))
    Yes '  and a 2, or anything but 0, stops the release' ($sky.Contains('if ($skyuiExit -eq 2)') -and $sky.Contains('if ($skyuiExit -ne 0)'))
    Yes 'main moves only once the dev feed carries the revision' ($ship -match "(?s)if \(\`$FromFeed -and \`$revMoveFrom\) \{.+if \(\`$Channel -eq 'main'\) \{.+Read-SiteFeed 'dev'.+if \(\`$carriedRev -ne \`$revBuilt\)")

    # ---- 4. Publish-Update.ps1 ----------------------------------------------
    Write-Host ''; Write-Host 'Publish-Update.ps1'
    $pu = [IO.File]::ReadAllText((Join-Path $rel 'Publish-Update.ps1'))
    Yes 'it moves the revision from the feed before it asks the record' ($pu.IndexOf('$feedMoveTo = Get-ShipFeedMoveRevision -RepoDir $RepoDir -Built $ShipCollectionRevision') -gt 0 -and
        $pu.IndexOf('$feedMoveTo = Get-ShipFeedMoveRevision') -lt $pu.IndexOf('$revWhy = Get-ShipCollectionRevisionProblem -RepoDir $RepoDir -Built $ShipCollectionRevision -Source "the $Channel feed''s last release"'))
    $iCarry = $pu.IndexOf("foreach (`$k in @(`$prev.Keys | Where-Object { `$_ -like ':profile:*' -or `$_ -like ':order:*' })) { `$now[`$k] = [string]`$prev[`$k] }")
    $iLists = $pu.IndexOf('$script:FeedMoveLists = New-ShipFeedMoveLists $RepoDir $feedGolden $feedLo')
    $iHash = $pu.IndexOf("`$now[':profile:plugins.txt'] = (Get-FileHash `$script:FeedMoveLists.Plugins")
    $iOrder = $pu.IndexOf('$feedOrder = Get-ShipFeedOrderProblem $feedBox.Order $feedEnabled')
    Yes 'the move''s list is written from the last release''s two lists' ($iLists -gt 0)
    Yes '  and its hashes and order key replace the ones carried forward' ($iHash -gt $iCarry -and $iCarry -gt 0 -and $pu.Contains("`$now[':order:shippedPlugins'] = Get-ActiveOrderKey `$script:FeedMoveLists.Plugins ''"))
    Yes '  and it is the list held to the server''s order' ($pu.Contains('$feedGolden = $script:FeedMoveLists.Plugins') -and $iOrder -gt $iHash)
    Yes 'the pack carries it as profile\plugins.txt and loadorder.txt, and the record as the golden list' ($pu -match '(?s)if \(\$part -eq \$groups\.Count -and \$FromFeed -and \$script:FeedMoveLists\) \{.+"profile/\$f".+Join-Path \$goldenDir \$f')
    Yes '"The server needs this too" is a Ship from One''s alone' ($pu.Contains('if ($profileChanged.Count -and -not $FromFeed) {'))
}
finally {
    Remove-Item -LiteralPath $T -Recurse -Force -ErrorAction SilentlyContinue
}
Write-Host ''
Write-Host ("{0} passed, {1} failed" -f $script:pass, $script:fail)
if ($script:fail) { exit 1 }
exit 0

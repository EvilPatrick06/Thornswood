<#
  test-nightly-plain-issues.ps1

      pwsh -NoProfile -File .\tests\test-nightly-plain-issues.ps1

  The nightly names every issue and comment made in the last day that is not
  written plain (#3692, Patrick's answer A on q-3692-new-issue-style:
  every new issue and comment is written plain, the evidence kept in the
  private ops repo). Developer-Guide.md "How an issue and a comment are
  written" is the rule.

  HOW. scripts\dev\Nightly-PlainIssues.ps1 is dot-sourced without -Run, so it
  only defines its functions, and Invoke-RestMethod is a stand-in here that
  keeps issues and comments in memory and answers the way GitHub does: pages
  of 100 by per_page and page, and a JSON array handed down the pipe as ONE
  object. Then:
    1. Each rule names what breaks it, and a plain issue, a plain comment, a
       test task and a stranger's long report are not named.
    2. 130 comments: the one on the second page is read.
    3. Nothing made before the rule's start, or more than a day ago, is read.
    4. A run that names nothing exits 0 and one that names something exits 1.
    5. nightly.yml runs the script, and the guide holds the rule.
  Never connects to anything.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$Here = $PSScriptRoot
if (-not $Here) { $Here = Split-Path -Parent $MyInvocation.MyCommand.Definition }
$repo = Split-Path -Parent $Here

$script:pass = 0
$script:fail = 0
function Yes([string]$what, [bool]$cond) {
    if ($cond) { $script:pass++; Write-Host "PASS  $what" }
    else { $script:fail++; Write-Host "FAIL  $what" }
}
function Done {
    Write-Host ''
    Write-Host ("{0} passed, {1} failed" -f $script:pass, $script:fail)
    if ($script:fail) { exit 1 }
    exit 0
}

$script:Issues = @()
$script:Comments = @()
$script:Asked = New-Object System.Collections.ArrayList

# GitHub, as far as this script uses it: one page of issues or comments, by
# per_page and page, as one object down the pipe (a single array).
function Invoke-RestMethod {
    param([string]$Method = 'GET', $Headers, [string]$Uri, $Body, [string]$ContentType)
    [void]$script:Asked.Add($Uri)
    $m = [regex]::Match($Uri, '/repos/[^/]+/[^/]+/(issues/comments|issues)\?(.*)$')
    if (-not $m.Success) { throw ('the stand-in does not answer ' + $Uri) }
    $q = @{}
    foreach ($kv in ($m.Groups[2].Value -split '&')) { $p = $kv -split '=', 2; $q[$p[0]] = $p[1] }
    $per = [int]$q['per_page']; $page = [int]$q['page']
    $list = if ($m.Groups[1].Value -eq 'issues') { $script:Issues } else { $script:Comments }
    $from = ($page - 1) * $per
    $slice = @()
    if ($from -lt $list.Count) { $slice = @($list[$from..([Math]::Min($list.Count, $from + $per) - 1)]) }
    Write-Output -NoEnumerate $slice
}

$env:REPO = 'EvilPatrick06/Thornswood'
$env:GH_TOKEN = 'not-a-real-token'
$scriptPath = Join-Path (Join-Path (Join-Path $repo 'scripts') 'dev') 'Nightly-PlainIssues.ps1'
. $scriptPath

# A time well after the rule started, so the day before it is read whole.
$now = [DateTime]::Parse('2026-11-05T12:00:00Z').ToUniversalTime()
$fresh = $now.AddHours(-2).ToString('o')
function Issue([int]$n, [string]$title, [string]$body, [string]$assoc = 'OWNER', [string]$type = 'User', [string]$at = $fresh) {
    [pscustomobject]@{ number = $n; title = $title; body = $body; created_at = $at; author_association = $assoc; user = [pscustomobject]@{ type = $type } }
}
function Comment([int]$n, [int]$id, [string]$body, [string]$assoc = 'OWNER', [string]$type = 'User', [string]$at = $fresh) {
    [pscustomobject]@{ id = $id; body = $body; created_at = $at; author_association = $assoc; user = [pscustomobject]@{ type = $type }
        issue_url = "https://api.github.com/repos/x/y/issues/$n"; html_url = "https://github.com/x/y/issues/$n#issuecomment-$id" }
}
function RulesOf($found, [string]$where) { @($found.Found | Where-Object { $_.Where -eq $where } | ForEach-Object { $_.Rules }) -join '|' }

# ---- 1. the rules ----------------------------------------------------------------
$plain = "The forge lists one ingot six times.`n`nDone when: each ingot is listed once."
$long = (1..12 | ForEach-Object { "line $_" }) -join "`n"
$script:Issues = @(
    (Issue 1 'Forge lists an ingot six times' $plain),
    (Issue 2 'Old style' ("Found by the Anvil audit (Quality), 26 Oct`n`n" + $plain)),
    (Issue 3 'Footer' ($plain + "`n`n---`n_Generated by [Claude Code](https://claude.ai/code)_")),
    (Issue 4 'Path' ('The log sits in C:\Users\someone\AppData. ' + $plain)),
    (Issue 5 'Id' ('Staff member 123456789012345678 saw it. ' + $plain)),
    (Issue 6 'Long' $long),
    (Issue 7 'A stranger' $long 'NONE'),
    (Issue 8 'Public folder' ('Setup reads C:\Users\Public\Desktop. ' + $plain)),
    (Issue 9 'Version' ('Seen on launcher 1.2.6.10. ' + $plain))
)
$pr = Issue 10 'A pull request' $long; $pr | Add-Member pull_request ([pscustomobject]@{ url = 'x' })
$script:Issues += $pr
$script:Comments = @(
    (Comment 1 101 'Still true on main today. The fix waits on the next Ship.'),
    (Comment 1 102 "Claimed by a Claude thread (26 Oct). This thread fixes it."),
    (Comment 1 103 ("Test task: Forge lists each ingot once`nServer: Main`n" + ((1..10 | ForEach-Object { "$_. step $_" }) -join "`n"))),
    (Comment 1 104 'The Smeagle lane read this again.'),
    (Comment 1 105 $long 'NONE' 'Bot'),
    (Comment 1 106 'Session: https://claude.ai/code/session_01ABC')
)
$f = Find-NotPlain -Now $now
Yes 'a plain issue is not named' ((RulesOf $f 'issue #1') -eq '')
Yes 'a byline opening the body is named' ((RulesOf $f 'issue #2') -match 'byline')
Yes 'a Claude Code footer is named' ((RulesOf $f 'issue #3') -match 'agent footer')
Yes 'a profile path with a name is named' ((RulesOf $f 'issue #4') -match 'personal path')
Yes 'a Discord id is named' ((RulesOf $f 'issue #5') -match 'Discord id')
Yes 'a team issue longer than the plain shape is named' ((RulesOf $f 'issue #6') -match 'longer than the plain shape \(12 lines\)')
Yes "a stranger's long report is not" ((RulesOf $f 'issue #7') -eq '')
Yes 'the Public profile folder is not a personal path' ((RulesOf $f 'issue #8') -eq '')
Yes 'a four-part version is not an id' ((RulesOf $f 'issue #9') -eq '')
Yes 'a pull request is left out' (@($f.Found | Where-Object { $_.Number -eq 10 }).Count -eq 0)
Yes 'a plain comment is not named' ((RulesOf $f 'https://github.com/x/y/issues/1#issuecomment-101') -eq '')
Yes 'a claim comment is named' ((RulesOf $f 'https://github.com/x/y/issues/1#issuecomment-102') -match 'byline')
Yes 'a test task keeps its own shape' ((RulesOf $f 'https://github.com/x/y/issues/1#issuecomment-103') -eq '')
Yes "a lane's name is named" ((RulesOf $f 'https://github.com/x/y/issues/1#issuecomment-104') -match 'byline')
Yes "a bot's long text is not measured" ((RulesOf $f 'https://github.com/x/y/issues/1#issuecomment-105') -eq '')
Yes 'a session link is named' ((RulesOf $f 'https://github.com/x/y/issues/1#issuecomment-106') -match 'agent footer')

# ---- 2. pages --------------------------------------------------------------------
$script:Issues = @()
$script:Comments = @(1..129 | ForEach-Object { Comment 1 (1000 + $_) 'Plain and short.' }) + @(Comment 1 2000 'Found by the Wyrd audit, again.')
$script:Asked.Clear()
$f = Find-NotPlain -Now $now
Yes ('every comment was read, past the first page ({0} of 130)' -f $f.Comments) ($f.Comments -eq 130)
Yes 'the second page was asked for' (@($script:Asked | Where-Object { $_ -match '/issues/comments\?since=.*&per_page=100&page=2$' }).Count -eq 1)
Yes 'the one on the second page is named' (@($f.Found | Where-Object { $_.Where -like '*issuecomment-2000' }).Count -eq 1)

# ---- 3. the window ---------------------------------------------------------------
$script:Comments = @()
$script:Issues = @(
    (Issue 20 'Two days old' ("Written by Smeagle`n" + $plain) 'OWNER' 'User' $now.AddDays(-2).ToString('o')),
    (Issue 21 'Before the rule' ("Written by Smeagle`n" + $plain) 'OWNER' 'User' '2026-10-27T12:00:00Z')
)
$f = Find-NotPlain -Now $now
Yes 'an issue made more than a day ago is not read' (@($f.Found).Count -eq 0)
$script:Issues = @($script:Issues[1])
$f = Find-NotPlain -Now ([DateTime]::Parse('2026-10-27T20:00:00Z').ToUniversalTime())
Yes 'nor one made before the rule started, whatever the day' (@($f.Found).Count -eq 0 -and $f.Since -eq '2026-10-27T13:00:00Z')
Yes 'the since GitHub is asked for is the window start' (@($script:Asked | Where-Object { $_ -match 'issues\?state=all&since=2026-10-27T13:00:00Z&' }).Count -ge 1)

# ---- 4. the run ------------------------------------------------------------------
$probe = @'
param([string]$ScriptPath, [string]$Body)
$ErrorActionPreference = 'Stop'
$global:Body = $Body
function Invoke-RestMethod {
    param([string]$Method = 'GET', $Headers, [string]$Uri)
    $list = @()
    if ($Uri -match '/issues\?' -and $Uri -match 'page=1$') {
        # An hour ago, or just after the rule started when this runs before it.
        $at = [DateTime]::UtcNow.AddHours(-1); $start = [DateTime]::Parse('2026-10-27T14:00:00Z').ToUniversalTime()
        if ($at -lt $start) { $at = $start }
        $list = @([pscustomobject]@{ number = 5; title = 'One'; body = $global:Body; created_at = $at.ToString('o'); author_association = 'OWNER'; user = [pscustomobject]@{ type = 'User' } })
    }
    Write-Output -NoEnumerate @($list)
}
$env:REPO = 'x/y'; $env:GH_TOKEN = 'not-a-real-token'
& $ScriptPath -Run
exit $LASTEXITCODE
'@
$probeFile = Join-Path ([IO.Path]::GetTempPath()) ('ts-plain-probe-' + [Guid]::NewGuid().ToString('N') + '.ps1')
[IO.File]::WriteAllText($probeFile, $probe)
try {
    $ps = (Get-Process -Id $PID).Path
    $out = & $ps -NoProfile -File $probeFile -ScriptPath $scriptPath -Body 'Short and plain. Done when: it works.' 2>&1 | Out-String
    $code0 = $LASTEXITCODE
    Yes ('a run that names nothing exits 0 and says so (exit {0})' -f $code0) ($code0 -eq 0 -and $out -match 'every new issue and comment is written plain')
    $out = & $ps -NoProfile -File $probeFile -ScriptPath $scriptPath -Body 'Found by the Anvil audit. Done when: it works.' 2>&1 | Out-String
    $code1 = $LASTEXITCODE
    Yes ('a run that names one exits 1 (exit {0})' -f $code1) ($code1 -eq 1)
    Yes '  and says which, which rule, and where the rule is written' ($out -match '::error::issue #5 is not written plain: byline' -and $out -match 'How an issue and a comment are written')
} finally {
    Remove-Item -LiteralPath $probeFile -Force -ErrorAction SilentlyContinue
}

# ---- 5. the nightly runs it, and the guide holds the rule -------------------------
$yml = [IO.File]::ReadAllText((Join-Path (Join-Path (Join-Path $repo '.github') 'workflows') 'nightly.yml'))
$a = $yml.IndexOf('- name: Issues and comments written plain')
$b = if ($a -ge 0) { $yml.IndexOf('- name:', $a + 10) } else { -1 }
$step = if ($a -ge 0 -and $b -gt $a) { $yml.Substring($a, $b - $a) } else { '' }
Yes 'nightly.yml has the step' ($step.Length -gt 0)
Yes 'it runs Nightly-PlainIssues.ps1 -Run with the token and the repository' (
    $step.Contains('.\scripts\dev\Nightly-PlainIssues.ps1 -Run') -and $step.Contains('GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}') -and
    $step.Contains('REPO: ${{ github.repository }}'))
$guide = [IO.File]::ReadAllText((Join-Path $repo 'Developer-Guide.md'))
Yes 'Developer-Guide.md has the rule under its own heading' ($guide.Contains('#### How an issue and a comment are written'))
$form = [IO.File]::ReadAllText((Join-Path (Join-Path (Join-Path $repo '.github') 'ISSUE_TEMPLATE') 'work.yml'))
Yes "the team's issue form asks only for the plain shape" ($form.Contains('Two to five plain lines') -and $form.Contains('label: Done when') -and -not $form.Contains('What causes it'))

Done

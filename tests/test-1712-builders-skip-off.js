// test-1712-builders-skip-off.js
//
// #1712. Vortex marks the plugins it has switched on with '*' in plugins.txt.
// Build-OreTable.ps1 and Build-BenchTable.py read every line and only stripped
// the '*', so a plugin Vortex had switched off was read as part of the build,
// and collection revision 2's five switched off plugins (three of them not in
// the game folder at all) stopped both. Build-RecipeTable.ps1 (#1622),
// Build-HarvestTable.ps1 and Build-HuntTable.ps1 already left them out.
//
// This runs both builders against a small Data folder made here: the five
// masters and two switched on plugins on disk, and a plugins.txt with two
// lines switched off, one of them a plugin that is not on disk. Both must take
// the switched on plugins, leave the two out, say so, and not stop on the
// missing one. Nothing outside a temporary folder is read or written.
//
// #2976. The same was still true of Build-DoorTable.py, Build-CastTable.py,
// Build-WellTable.py and the fire, warmth, water and weather builders, which
// parsed plugins.txt on their own: on 20 Oct the door builder stopped on
// ElysiumEstateSSE.esp, a switched off line whose file the launcher had removed.
// They all read the load order through scripts/dev/OwnPlugins.js and
// own_plugins.py now, and are run here on the same folder. And a builder that
// reads every plugin of the load order stops on a switched on plugin that is
// not on disk, rather than building a table of a load order nobody runs.
const REPO_DIR = require("path").join(__dirname, "..");
const fs = require("fs");
const os = require("os");
const path = require("path");
const cp = require("child_process");

let pass = 0, fail = 0;
function yes(what, cond) {
  if (cond) { pass++; console.log("PASS  " + what); }
  else { fail++; console.log("FAIL  " + what); }
}

// A plugin with nothing in it but its TES4 header: no records, not localised,
// no masters. Both builders read the header and walk zero groups.
function plugin(file) {
  const hedr = Buffer.alloc(6 + 12);
  hedr.write("HEDR", 0, "ascii");
  hedr.writeUInt16LE(12, 4);
  hedr.writeFloatLE(1.7, 6);
  const head = Buffer.alloc(24);
  head.write("TES4", 0, "ascii");
  head.writeUInt32LE(hedr.length, 4);
  fs.writeFileSync(file, Buffer.concat([head, hedr]));
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "tw-1712-"));
const data = path.join(tmp, "Data");
fs.mkdirSync(data);
const ON = ["Skyrim.esm", "Update.esm", "Dawnguard.esm", "HearthFires.esm", "Dragonborn.esm", "On One.esp", "On Two.esp"];
const SWITCHED_OFF_ON_DISK = "Off On Disk.esp";
for (const p of ON.concat([SWITCHED_OFF_ON_DISK])) { plugin(path.join(data, p)); }
const pluginsTxt = path.join(tmp, "plugins.txt");
fs.writeFileSync(pluginsTxt, [
  "# Automatically generated by Vortex",
  "*On One.esp",
  SWITCHED_OFF_ON_DISK,
  "Off Not On Disk.esp",
  "*On Two.esp",
  ""
].join("\r\n"));
const recipes = path.join(tmp, "recipes.json");
fs.writeFileSync(recipes, JSON.stringify({ recipes: {}, unowned: {} }));
const gamemode = path.join(tmp, "gamemode.js");
fs.writeFileSync(gamemode, "// nothing\n");

function run(cmd, args) {
  const r = cp.spawnSync(cmd, args, { encoding: "utf8", timeout: 120000 });
  return { ok: !r.error, code: r.status, out: String(r.stdout || "") + String(r.stderr || "") };
}

try {
  // ---- Build-BenchTable.py ---------------------------------------------
  const py = ["python", "python3"].map(function (c) { return { c: c, r: run(c, ["--version"]) }; })
    .filter(function (x) { return x.r.ok && x.r.code === 0; })[0];
  yes("python is on this machine, so the bench builder can be run", !!py);
  if (py) {
    const b = run(py.c, [path.join(REPO_DIR, "scripts", "dev", "Build-BenchTable.py"),
      "--data", data, "--plugins", pluginsTxt, "--recipes", recipes, "--gamemode", gamemode, "--check"]);
    yes("Build-BenchTable.py runs to the end with a switched off plugin missing from the folder (exit " + b.code + ")", b.code === 0);
    yes("it does not stop on a plugin that is not in the folder", b.out.indexOf("STOP.") < 0);
    yes("it says it left the two switched off lines out",
      b.out.indexOf("2 line(s) in that list are switched off and were left out") >= 0);
    yes("it reads the five masters and the two switched on plugins, and nothing else",
      b.out.indexOf("7 plugin(s): the five masters, then") >= 0 && b.out.indexOf("7 plugin(s) read") >= 0);
    yes("--check wrote nothing into the gamemode", fs.readFileSync(gamemode, "utf8") === "// nothing\n");
    if (b.code !== 0) { console.log(b.out.split("\n").slice(-15).join("\n")); }
  }

  // ---- Build-OreTable.ps1 ----------------------------------------------
  // The table is empty here, so the ore checks further down fail and the run
  // exits 1 without writing; only the load order part is held.
  const ps = run("pwsh", ["--version"]);
  yes("pwsh is on this machine, so the ore builder can be run", ps.ok && ps.code === 0);
  if (ps.ok && ps.code === 0) {
    const out = path.join(tmp, "ores.json");
    const o = run("pwsh", ["-NoProfile", "-File", path.join(REPO_DIR, "scripts", "dev", "Build-OreTable.ps1"),
      "-Data", data, "-PluginsTxt", pluginsTxt, "-Out", out, "-NoInstall"]);
    yes("Build-OreTable.ps1 finds every plugin of its load order on disk",
      o.out.indexOf("every plugin in the load order is on disk") >= 0 && o.out.indexOf("are not in " + data) < 0);
    yes("it says it left the two switched off lines out",
      o.out.indexOf("2 line(s) in that list are switched off and were left out") >= 0);
    yes("it reads the five masters and the two switched on plugins, and nothing else",
      o.out.indexOf("7 plugins: the five masters, then") >= 0);
    yes("it went on past the load order to the records", /0 veins in all/.test(o.out));
    if (o.out.indexOf("every plugin in the load order is on disk") < 0 || !/0 veins in all/.test(o.out)) {
      console.log(o.out.split("\n").slice(0, 40).join("\n"));
    }
  }

  // ---- #2976: the door, cast and well builders ---------------------------
  if (py) {
    const out = path.join(tmp, "out.json");
    for (const b of ["Build-DoorTable.py", "Build-CastTable.py", "Build-WellTable.py"]) {
      const a = [path.join(REPO_DIR, "scripts", "dev", b), "--data", data, "--plugins", pluginsTxt, "--out", out, "--check"];
      if (b !== "Build-CastTable.py") { a.push("--gamemode", gamemode); }
      const r = run(py.c, a);
      // The well builder stops later, on well bases this folder has none of.
      if (b !== "Build-WellTable.py") {
        yes(b + " takes the five masters and the two switched on plugins, and nothing else",
          r.out.indexOf("7 plugins, the five masters then") >= 0);
      }
      yes(b + " does not stop on, skip or name a switched off plugin",
        r.out.indexOf("STOP. 1 plugin") < 0 && r.out.indexOf("skipped") < 0 && r.out.indexOf("Off ") < 0);
      if (r.out.indexOf("Off ") >= 0 || r.out.indexOf("STOP. 1 plugin") >= 0) { console.log(r.out.split("\n").slice(0, 10).join("\n")); }
    }
    yes("--check wrote nothing into the gamemode", fs.readFileSync(gamemode, "utf8") === "// nothing\n");
  }

  // ---- #2976: the fire, warmth, water and weather builders ---------------
  // Their tables are empty here, so their own checks fail and they write
  // nothing; only the load order they read is held.
  const out = path.join(tmp, "out.json");
  const said = { "Build-FireTable.js": "7 plugins in the order", "Build-WarmthTable.js": "7 plugins read",
                 "Build-WaterTable.js": "7 plugins read", "Build-WeatherTable.js": "7 plugins read" };
  for (const b of Object.keys(said)) {
    const r = run(process.execPath, [path.join(REPO_DIR, "scripts", "dev", b), "--data", data, "--plugins", pluginsTxt, "--out", out]);
    yes(b + " reads the five masters and the two switched on plugins, and nothing else", r.out.indexOf(said[b]) >= 0);
    if (r.out.indexOf(said[b]) < 0) { console.log(r.out.split("\n").slice(-8).join("\n")); }
  }
  yes("and none of them wrote a table", !fs.existsSync(out));
  const onGone = path.join(tmp, "plugins-on-gone.txt");
  fs.writeFileSync(onGone, "*On One.esp\r\n*On Not On Disk.esp\r\n");
  const g = run(process.execPath, [path.join(REPO_DIR, "scripts", "dev", "Build-FireTable.js"), "--data", data, "--plugins", onGone, "--out", out]);
  yes("a switched on plugin that is not on disk stops Build-FireTable.js, by name (exit " + g.code + ")",
    g.code === 1 && g.out.indexOf("STOP. 1 plugin(s) are not in " + data + ": On Not On Disk.esp") >= 0);
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}

console.log("");
console.log(pass + " passed, " + fail + " failed");
process.exit(fail ? 1 : 0);
